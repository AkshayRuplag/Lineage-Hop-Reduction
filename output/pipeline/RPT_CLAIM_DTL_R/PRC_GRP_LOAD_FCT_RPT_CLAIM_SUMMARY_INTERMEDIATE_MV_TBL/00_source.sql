    --First Closed Status Effective Date (July 2024)
    LEFT JOIN
        CLAIM_FIRST_CLOSED_STAT_EFF_DATE CFCSED
    ON
        CFCSED.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND CFCSED.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
