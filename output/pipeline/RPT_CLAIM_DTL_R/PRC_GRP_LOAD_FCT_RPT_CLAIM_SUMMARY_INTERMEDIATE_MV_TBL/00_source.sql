					  -- AND EXTRACT (YEAR FROM T.D_CALENDAR_DATE_R    )= TO_NUMBER(TO_CHAR(to_date('29-JUL-25','DD-MON-YY'), 'YYYY'))
                        T.n_fiscal_month_r  = TO_NUMBER(TO_CHAR(D_CURR_FISCAL_DATE, 'MM'))
                       AND T.n_fiscal_year_r   = TO_NUMBER(TO_CHAR(D_CURR_FISCAL_DATE, 'YYYY'))
					   --AND CP.V_CLAIM_NUMBER_R LIKE 'BC-2025-183586-VAI-01%'
