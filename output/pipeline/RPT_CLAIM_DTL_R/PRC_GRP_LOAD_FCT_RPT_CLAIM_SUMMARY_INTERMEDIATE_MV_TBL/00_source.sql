'FIC'
,'MED'
)
THEN (CP.N_PAID_AMOUNT_R)
ELSE NVL(CP.N_PAID_AMOUNT_R, 0)
END),0)
ELSE

					CASE
						WHEN CP.V_COVERAGE_CODE_R IN ('VAI', 'VCI', 'VHI') THEN
							(SUM(CP.N_PAID_AMOUNT_R))

						ELSE
							NVL(SUM(
								CASE
									WHEN CP.V_RECORD_TYPE_R = 'Redirect' THEN CP.N_PAID_AMOUNT_R
									WHEN CP.V_BENEFIT_CODE_R IN ('FIC', 'MED') AND CP.V_RECORD_TYPE_R = 'Benefit Payment' THEN CP.N_PAID_CLAIM_BENEFITS_R * -1
