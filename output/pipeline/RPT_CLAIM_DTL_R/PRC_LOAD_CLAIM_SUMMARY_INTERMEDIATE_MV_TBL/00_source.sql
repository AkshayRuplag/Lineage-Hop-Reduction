

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ATOMIC"."PRC_LOAD_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL"
(
	P_N_BATCH_ID_R		IN		NUMBER
)
AS
    V_SYS_DATE                	VARCHAR2(15) := TO_CHAR(SYSDATE, 'YYYYMMDDHHMISS');
	N_BATCH_ID_R				NUMBER 		 := P_N_BATCH_ID_R;
    N_MAX_SERIAL_NUM_R        	NUMBER;
    V_SQLCODE                 	VARCHAR2(100);
    V_SQLERRM                 	VARCHAR2(500);
	D_PRIOR_FISCAL_DATE 		DATE;
	D_CURR_FISCAL_DATE 			DATE;
	D_CYCLE_DATE_R 				DATE;
	D_MAXRESERVAL_DATE_R 		DATE;
BEGIN
	/* PRIOR FISC DATE */
	SELECT
        MAX(DTR.D_CALENDAR_DATE_R)
    INTO
        D_PRIOR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R < TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
            AND V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    ) DTR_PRIOR
    JOIN DIM_TIME_R DTR
    ON
        DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
        AND DTR.N_FISCAL_MONTH_R = DTR_PRIOR.N_FISCAL_MONTH_R
        AND DTR.N_FISCAL_YEAR_R = DTR_PRIOR.N_FISCAL_YEAR_R;

	/* CURRENT FISCAL DATE */
	SELECT
		DTR.D_CALENDAR_DATE_R
    INTO
		D_CURR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* CYCLE DATE */
    SELECT
		DTR.D_CALENDAR_DATE_R
    INTO
		D_CYCLE_DATE_R
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* TRUNCATE THE TABLE FIRST */
	EXECUTE IMMEDIATE 'TRUNCATE TABLE CLAIM_SUMMARY_INTERMEDIATE_MV_TBL PURGE SNAPSHOT LOG';
	INSERT INTO CLAIM_SUMMARY_INTERMEDIATE_MV_TBL(
		V_CLAIM_IDENTIFIER_R,
		N_TOTAL_NO_OF_PAYMENTS_R,
		N_NO_OF_PAYMENTS_R,
		N_NO_OF_CHECKS_R,
		N_PRIOR_N_REOPEN_CLAIM_CNT_R,
		V_COVERAGE_CODE_R,
		D_SERVICE_PERIOD_FROM_R,
		V_LOB_TYPE_R,
		D_DATE_CLOSED_R
	)
	SELECT
		CLMSUMD.V_CLAIM_IDENTIFIER_R,
		CLMSUMD.N_TOTAL_NO_OF_PAYMENTS_R,
		CLMSUMD.N_NO_OF_PAYMENTS_R,
		CLMSUMD.N_NO_OF_CHECKS_R,
		CLMSUMD.N_PRIOR_N_REOPEN_CLAIM_CNT_R,
		CLMSUMD.V_COVERAGE_CODE_R,
		CLMSUMD.D_SERVICE_PERIOD_FROM_R,
		CLMSUMD.V_LOB_TYPE_R,
		CLMSUMD.D_DATE_CLOSED_R
	FROM (
		WITH CLAIM_SUM_DTLS AS (
			SELECT
				D_SERVICE_PERIOD_FROM_R,
				V_CHECK_NUMBER_R,
				N_FISCAL_MONTH_R,
				N_FISCAL_YEAR_R,
				V_PAYMENT_STATUS_R,
				DCOV.V_CLAIM_IDENTIFIER_R,
				DCOV.V_COVERAGE_CODE_R,
				RC.N_REOPEN_CLAIM_COUNT_R,
				CD.V_LOB_TYPE_R,
				NVL(DCOV.D_DATE_CLOSED_R, CDTL.D_CLOSURE_DATE_R)									AS D_DATE_CLOSED_R, --Added in July 2024: If the claim is not a Life/WOP claim, then take from Claim Detail
				TO_NUMBER(TO_CHAR(D_CURR_FISCAL_DATE, 'YYYYMM')) 									AS N_CURR_FISC_R,
				TO_NUMBER(TO_CHAR(D_PRIOR_FISCAL_DATE, 'YYYYMM')) 									AS N_PRIOR_FISC_R
			FROM
				  DIM_GRP_CLAIM_DIR_R CD
			LEFT JOIN
				DIM_GRP_CLAIM_DETAIL_R CDTL --Added for bringing in Claim Closure date in case of LOB <> 'Life' (July 2024)
			ON
				CDTL.N_CLAIM_SK_R = CD.N_CLAIM_SK_R
				AND CD.V_ACTIVE_STATUS_R = 'Y'
				AND CDTL.V_ACTIVE_STATUS_R = 'Y'
			LEFT JOIN
				DIM_GRP_CLAIM_COVERAGE_GROUP_R DCOV
			ON
				CD.V_CLAIM_NUMBER_R = DCOV.V_CLAIM_NUMBER_R
				AND DCOV.V_ACTIVE_STATUS_R = 'Y'
			LEFT JOIN
				ATOMIC.FCT_CLAIM_PAYMENT_DETAIL_R_MV3 CP
			ON
				CP.V_CLAIM_IDENTIFIER_R = DCOV.V_CLAIM_IDENTIFIER_R
				AND CP.N_FISCAL_MONTH_R = TO_NUMBER(TO_CHAR(D_CURR_FISCAL_DATE, 'MM'))
				AND CP.N_FISCAL_YEAR_R = TO_NUMBER(TO_CHAR(D_CURR_FISCAL_DATE, 'YYYY'))
				AND CP.V_PAYMENT_STATUS_R = 'PAID'
                AND NVL(CP.V_RECORD_TYPE_R, '@') <> 'Expense'
			LEFT JOIN (
				SELECT V_COVERAGE_CODE_R,
					V_CLAIM_IDENTIFIER_R,
					N_REOPEN_CLAIM_COUNT_R
				FROM
					ATOMIC.FCT_RPT_CLAIM_SUMMARY_R
				WHERE
					TO_NUMBER(TO_CHAR(D_CYCLE_DATE_R, 'YYYYMM')) = TO_NUMBER(TO_CHAR(D_PRIOR_FISCAL_DATE, 'YYYYMM'))
				) RC
				ON CP.V_CLAIM_IDENTIFIER_R = RC.V_CLAIM_IDENTIFIER_R

			GROUP BY D_SERVICE_PERIOD_FROM_R,
				V_CHECK_NUMBER_R,
				N_FISCAL_MONTH_R,
				N_FISCAL_YEAR_R,
				V_PAYMENT_STATUS_R,
				DCOV.V_CLAIM_IDENTIFIER_R,
				DCOV.V_COVERAGE_CODE_R,
				RC.N_REOPEN_CLAIM_COUNT_R,
				CD.V_LOB_TYPE_R,
				NVL(DCOV.D_DATE_CLOSED_R, CDTL.D_CLOSURE_DATE_R)
		)
		SELECT
			V_CLAIM_IDENTIFIER_R,
			COUNT(CASE
					WHEN V_PAYMENT_STATUS_R = 'PAID'
						THEN 1
					END) AS n_total_no_of_payments_r,
			COUNT(CASE
					WHEN N_FISCAL_MONTH_R = TO_NUMBER(SUBSTR(TRIM(N_CURR_FISC_R), 5, 2))
						AND N_FISCAL_YEAR_R = TO_NUMBER(SUBSTR(N_CURR_FISC_R, 1, 4))
						AND V_PAYMENT_STATUS_R = 'PAID'
						THEN 1
					END) AS n_no_of_payments_r,
			COUNT(CASE
					WHEN N_FISCAL_MONTH_R = TO_NUMBER(SUBSTR(TRIM(N_CURR_FISC_R), 5, 2))---TO_NUMBER(SUBSTR(N_CURR_FISC_R, 5, 6))
						AND N_FISCAL_YEAR_R = TO_NUMBER(SUBSTR(TRIM(N_CURR_FISC_R), 1, 4)) ---TO_NUMBER(SUBSTR(N_CURR_FISC_R, 1, 4))
						AND V_PAYMENT_STATUS_R     = 'PAID'
						THEN V_CHECK_NUMBER_R
					END) n_no_of_checks_r,
			SUM(N_REOPEN_CLAIM_COUNT_R) AS n_prior_n_reopen_claim_cnt_r,
			V_COVERAGE_CODE_R,
			MIN(D_SERVICE_PERIOD_FROM_R) AS D_SERVICE_PERIOD_FROM_R,
			V_LOB_TYPE_R,
			D_DATE_CLOSED_R
		FROM
			CLAIM_SUM_DTLS
		GROUP BY V_CLAIM_IDENTIFIER_R, V_COVERAGE_CODE_R, V_LOB_TYPE_R, D_DATE_CLOSED_R
	) CLMSUMD;
	COMMIT;
EXCEPTION
WHEN OTHERS THEN
V_SQLERRM := SUBSTR(SQLERRM, 1, 4000);
	   RAISE_APPLICATION_ERROR(-20111, 'Raise Application Error in PRC_LOAD_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL :->' || V_SQLERRM);
END;

