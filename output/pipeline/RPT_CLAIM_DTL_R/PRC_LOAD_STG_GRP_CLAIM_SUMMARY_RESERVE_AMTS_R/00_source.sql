

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ATOMIC"."PRC_LOAD_STG_GRP_CLAIM_SUMMARY_RESERVE_AMTS_R"
(
	P_N_BATCH_ID_R		IN		NUMBER
)
AS
    V_SYS_DATE                	VARCHAR2(15) := TO_CHAR(SYSDATE, 'YYYYMMDDHHMISS');
	LN_BATCH_ID_R				NUMBER 		 := P_N_BATCH_ID_R;
    N_MAX_SERIAL_NUM_R        	NUMBER;
    V_SQLCODE                 	VARCHAR2(100);
    V_SQLERRM                 	VARCHAR2(500);
	D_PRIOR_FISCAL_DATE 		DATE;
	D_CURR_FISCAL_DATE 			DATE;
	D_CYCLE_DATE_R 				DATE;
	D_MAXRESERVAL_DATE_R 		DATE;
BEGIN
	/* PRIOR FISC DATE */
	SELECT
        MAX(DTR.D_CALENDAR_DATE_R)
    INTO
        D_PRIOR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R < TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
            AND V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    ) DTR_PRIOR
    JOIN DIM_TIME_R DTR
    ON
        DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
        AND DTR.N_FISCAL_MONTH_R = DTR_PRIOR.N_FISCAL_MONTH_R
        AND DTR.N_FISCAL_YEAR_R = DTR_PRIOR.N_FISCAL_YEAR_R;

	/* CURRENT FISCAL DATE */
	SELECT
        DTR.D_CALENDAR_DATE_R
    INTO
        D_CURR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* CYCLE DATE */
    SELECT
        DTR.D_CALENDAR_DATE_R
    INTO
        D_CYCLE_DATE_R
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* MAX RESERVE VALUATION DATE */
    SELECT
        DTR.D_CALENDAR_DATE_R
    INTO
        D_MAXRESERVAL_DATE_R
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* TRUNCATE THE TABLE FIRST */
	EXECUTE IMMEDIATE 'TRUNCATE TABLE STG_GRP_CLAIM_SUMMARY_RESERVE_AMTS_R PURGE SNAPSHOT LOG';
	INSERT INTO STG_GRP_CLAIM_SUMMARY_RESERVE_AMTS_R(
		N_CLAIM_SK_R,
		V_CLAIM_STATUS_REASON_CODE_R,
		V_REASON_CODE_R,
		T_EVENT_TIMESTAMP_R_1,
		T_EVENT_TIMESTAMP_R_2,
		V_REASON_FLAG_R,
		V_CLAIM_NUMBER_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		V_CLAIM_IDENTIFIER_R,
		V_CLAIM_COVERAGE_CODE_R,
		N_POLICY_SK_R,
		V_POLICY_NUMBER_R,
		D_PAYMENT_LAST_DATE_R,
		N_CURR_GAAP_RESERVE_DIRECT_R,
		N_CHG_GAAP_OS_DIRECT_AMT_R,
		D_PRIOR_FISCAL_DATE,
		D_CURR_FISCAL_DATE,
		D_CYCLE_DATE_R,
		D_MAXRESERVAL_DATE_R,
		N_CURR_STAT_RESERVE_DIRECT_R,
		N_CURR_FIELD_RES_DIRECT_AMT_R,
		N_CURR_BE_RESERVE_DIRECT_AMT_R,
		N_CHG_STAT_OS_DIRECT_AMT_R,
		N_CHG_FIELD_RES_DIRECT_AMT_R,
		N_CHG_BE_RESERVE_DIRECT_AMT_R
	)
	WITH RESERVE_PAYMENT_DTLS AS(
		SELECT
			FCPDRMV2.D_PAID_DATE_R 							AS 			D_PAYMENT_LAST_DATE_R,
			FLRDTLR.N_CURR_GAAP_RESERVE_DIRECT_R,
			FLRDTLR.N_CHG_GAAP_OS_DIRECT_AMT_R,
			FLRDTLR.N_CURR_STAT_RESERVE_DIRECT_R,
			FLRDTLR.N_CURR_FIELD_RES_DIRECT_AMT_R,
			FLRDTLR.N_CURR_BE_RESERVE_DIRECT_AMT_R,
			FLRDTLR.N_CHG_STAT_OS_DIRECT_AMT_R,
			FLRDTLR.N_CHG_FIELD_RES_DIRECT_AMT_R,
			FLRDTLR.N_CHG_BE_RESERVE_DIRECT_AMT_R,
			D_PRIOR_FISCAL_DATE,
			D_CURR_FISCAL_DATE,
			D_CYCLE_DATE_R,
			D_MAXRESERVAL_DATE_R,
			DGCDRM.*
		FROM
			DIM_GRP_CLAIM_DETAIL_R_MV DGCDRM
		LEFT JOIN
			FCT_CLAIM_PAYMENT_DETAIL_R_MV2 FCPDRMV2
		ON
			FCPDRMV2.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
            AND FCPDRMV2.V_CLAIM_IDENTIFIER_R = DGCDRM.V_CLAIM_IDENTIFIER_R
		LEFT JOIN (
			SELECT
				V_CLAIM_IDENTIFIER_R,
				--V_COVERAGE_CODE_R,
				SUM(N_RESERVE_DIRECT__GAAP__R) 						AS 			N_CURR_GAAP_RESERVE_DIRECT_R,
				SUM(N_CHG_RESERVE_DIRECT__GAAP__R)					AS 			N_CHG_GAAP_OS_DIRECT_AMT_R,
				MAX(N_RESERVE_DIRECT__STAT__R) 						AS 			N_CURR_STAT_RESERVE_DIRECT_R,
				MAX(N_RESERVE_DIRECT__FIELD__R)						AS 			N_CURR_FIELD_RES_DIRECT_AMT_R,
				MAX(N_RESERVE_DIRECT_BEST_ESTMT_R)					AS			N_CURR_BE_RESERVE_DIRECT_AMT_R,
				MAX(N_CHG_RESERVE_DIRECT__STAT__R)					AS 			N_CHG_STAT_OS_DIRECT_AMT_R,
				MAX(N_CHG_RESERVE_DIRECT__FIELD__R)					AS			N_CHG_FIELD_RES_DIRECT_AMT_R,
				MAX(N_CHG_RSRV_DIRECT_BEST_ESTMT_R)					AS			N_CHG_BE_RESERVE_DIRECT_AMT_R
			FROM
				FCT_LG_RESERVE_DETAILS_R
			WHERE
				V_RESERVE_TYPE_IND_R = 'L'
				AND D_RESERVE_VALUATION_DATE_R = D_MAXRESERVAL_DATE_R
				AND V_CLAIM_IDENTIFIER_R IS NOT NULL
			GROUP BY
				V_CLAIM_IDENTIFIER_R
				--,V_COVERAGE_CODE_R
		) FLRDTLR
		ON
			FLRDTLR.V_CLAIM_IDENTIFIER_R = DGCDRM.V_CLAIM_IDENTIFIER_R
			--AND FLRDTLR.V_COVERAGE_CODE_R = DGCDRM.V_CLAIM_COVERAGE_CODE_R
	),
	REASON_FLAG_DTLS AS(
		SELECT
			CASE
			WHEN (
					(NVL(RPD.V_REASON_CODE_R, RPD.V_CLAIM_STATUS_REASON_CODE_R) <= '59')
					OR (
						NVL(RPD.V_REASON_CODE_R, RPD.V_CLAIM_STATUS_REASON_CODE_R) > '59'
						AND TRUNC(DCPSR.D_CLAIM_STATUS_CODE_EFF_DATE_R) BETWEEN TRUNC(RPD.D_PRIOR_FISCAL_DATE)
							AND TRUNC(RPD.D_CURR_FISCAL_DATE)
						)
					OR (
						NVL(RPD.V_REASON_CODE_R, RPD.V_CLAIM_STATUS_REASON_CODE_R) > '59'
						AND TRUNC(RPD.D_PAYMENT_LAST_DATE_R) >= TRUNC(RPD.D_PRIOR_FISCAL_DATE)
						)
					OR (
						NVL(RPD.V_REASON_CODE_R, RPD.V_CLAIM_STATUS_REASON_CODE_R) > '59'
						AND NVL(RPD.N_CURR_GAAP_RESERVE_DIRECT_R, 0) <> 0
						)
					OR (
						NVL(RPD.V_REASON_CODE_R, RPD.V_CLAIM_STATUS_REASON_CODE_R) > '59'
						AND (RPD.N_CHG_GAAP_OS_DIRECT_AMT_R) <> 0
						)
				)
					THEN 'Y'
			ELSE
					'N'
			END 											AS 			V_REASON_FLAG_R1,
			RPD.*
			FROM
				RESERVE_PAYMENT_DTLS RPD
			LEFT JOIN (
				SELECT
					N_CLAIM_SK_R,
                    N_CLAIM_COVERAGE_SK_R,
					N_CLAIM_COVERAGE_GROUP_SK_R,
                    V_CURR_CLAIM_STATUS_CODE_R,
                    MAX(D_CLAIM_STATUS_CODE_EFF_DATE_R) 	AS 			D_CLAIM_STATUS_CODE_EFF_DATE_R,
                    RANK() OVER(
						PARTITION BY
							N_CLAIM_SK_R,
							N_CLAIM_COVERAGE_SK_R,
							N_CLAIM_COVERAGE_GROUP_SK_R
                        --Added Aug 2024, because some (mainly Shinka) claims have incorrect duplicate records with same Claim SK
						ORDER BY
                            T_EVENT_TIMESTAMP_R DESC NULLS LAST,
                            MAX(D_CLAIM_STATUS_CODE_EFF_DATE_R) DESC NULLS LAST
					) RNK
				FROM
					DIM_GRP_CLAIM_PRIOR_STATUS_R
                WHERE
                    TO_DATE(SUBSTR(N_BATCH_ID_R, 1, 8), 'YYYYMMDD') <= TRUNC(D_CURR_FISCAL_DATE) /* Oct 2024, for checking */
                GROUP BY
                    N_CLAIM_SK_R,
                    N_CLAIM_COVERAGE_SK_R,
					N_CLAIM_COVERAGE_GROUP_SK_R,
                    V_CURR_CLAIM_STATUS_CODE_R,
                    T_EVENT_TIMESTAMP_R
			) DCPSR
			ON
				DCPSR.N_CLAIM_SK_R = RPD.N_CLAIM_SK_R
				AND DCPSR.N_CLAIM_COVERAGE_SK_R = RPD.N_CLAIM_COVERAGE_SK_R
				AND DCPSR.N_CLAIM_COVERAGE_GROUP_SK_R = RPD.N_CLAIM_COVERAGE_GROUP_SK_R
				AND DCPSR.RNK = 1
	)
	SELECT
		N_CLAIM_SK_R,
		V_CLAIM_STATUS_REASON_CODE_R,
		V_REASON_CODE_R,
		T_EVENT_TIMESTAMP_R_1,
		T_EVENT_TIMESTAMP_R_2,
		V_REASON_FLAG_R1 									AS			V_REASON_FLAG_R,
		V_CLAIM_NUMBER_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		V_CLAIM_IDENTIFIER_R,
		V_CLAIM_COVERAGE_CODE_R,
		N_POLICY_SK_R,
		V_POLICY_NUMBER_R,
		D_PAYMENT_LAST_DATE_R,
		N_CURR_GAAP_RESERVE_DIRECT_R,
		N_CHG_GAAP_OS_DIRECT_AMT_R,
		D_PRIOR_FISCAL_DATE,
		D_CURR_FISCAL_DATE,
		D_CYCLE_DATE_R,
		D_MAXRESERVAL_DATE_R,
		N_CURR_STAT_RESERVE_DIRECT_R,
		N_CURR_FIELD_RES_DIRECT_AMT_R,
		N_CURR_BE_RESERVE_DIRECT_AMT_R,
		N_CHG_STAT_OS_DIRECT_AMT_R,
		N_CHG_FIELD_RES_DIRECT_AMT_R,
		N_CHG_BE_RESERVE_DIRECT_AMT_R
	FROM
		REASON_FLAG_DTLS;
	COMMIT;
EXCEPTION
WHEN OTHERS THEN
V_SQLERRM := SUBSTR(SQLERRM, 1, 4000);
	   RAISE_APPLICATION_ERROR(-20111, 'Raise Application Error in PRC_LOAD_STG_GRP_CLAIM_SUMMARY_RESERVE_AMTS_R :->' || V_SQLERRM);
END;

