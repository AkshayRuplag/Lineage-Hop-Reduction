

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ATOMIC"."PRC_LOAD_STG_GRP_CLAIM_SUMMARY_PAYMENT_DETAILS_R"
(
	P_N_BATCH_ID_R		IN		NUMBER
)
AS
    V_SYS_DATE                	VARCHAR2(15) := TO_CHAR(SYSDATE, 'YYYYMMDDHHMISS');
	N_BATCH_ID_R				NUMBER 		 := P_N_BATCH_ID_R;
    N_MAX_SERIAL_NUM_R        	NUMBER;
    V_SQLCODE                 	VARCHAR2(100);
    V_SQLERRM                 	VARCHAR2(500);
	D_PRIOR_FISCAL_DATE 		DATE;
	D_CURR_FISCAL_DATE 			DATE;
	D_CYCLE_DATE_R 				DATE;
	D_MAXRESERVAL_DATE_R 		DATE;
BEGIN
	/* PRIOR FISC DATE */
	SELECT
        MAX(DTR.D_CALENDAR_DATE_R)
    INTO
        D_PRIOR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R < TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
            AND V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    ) DTR_PRIOR
    JOIN DIM_TIME_R DTR
    ON
        DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
        AND DTR.N_FISCAL_MONTH_R = DTR_PRIOR.N_FISCAL_MONTH_R
        AND DTR.N_FISCAL_YEAR_R = DTR_PRIOR.N_FISCAL_YEAR_R;

	/* CURRENT FISC DATE */
	SELECT
		DTR.D_CALENDAR_DATE_R
    INTO
		D_CURR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* CYCLE DATE */
    SELECT
		DTR.D_CALENDAR_DATE_R
    INTO
		D_CYCLE_DATE_R
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* MAX RESERVE VALUATION DATE */
    SELECT
		DTR.D_CALENDAR_DATE_R
    INTO
		D_MAXRESERVAL_DATE_R
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* TRUNCATE THE TABLE FIRST */
	EXECUTE IMMEDIATE 'TRUNCATE TABLE STG_GRP_CLAIM_SUMMARY_PAYMENT_DETAILS_R PURGE SNAPSHOT LOG';
	INSERT INTO STG_GRP_CLAIM_SUMMARY_PAYMENT_DETAILS_R(
		N_WAGE_BASE_R,
		N_PAYMENT_TAXABLE_BENEFITS_R,
		N_PAYMENT_NONTAXABLE_BEN_R,
		N_NON_TAXABLE_BENEFITS_R,
		N_MEDICARE_WAGE_BASE_R,
		N_EMP_MEDICARE_WAGE_BASE_R,
		N_EMP_FICA_WAGE_BASE_R,
		N_TAXABLE_BENEFITS_R,
		N_SIT_R,
		N_PAYMENT_DIRECT_AMT_R,
		N_MEDICARE_TAX_R,
		N_FUTA_R,
		N_FIT_R,
		N_FICA_WAGE_BASE_R,
		N_FICA_R,
		N_EMPLOYER_MEDICARE_TAX_R,
		N_EMPLOYER_FICA_R,
		D_LAST_PAYMENT_TO_DATE_R,
		D_FIRST_PAYMENT_FROM_DATE_R,
		N_CURR_STAT_WV_DIRECT_AMT_R,
		N_CURR_GAAP_WV_DIRECT_AMT_R,
		N_CHG_STAT_WV_DIRECT_AMT_R,
		N_CHG_GAAP_WV_DIRECT_AMT_R,
		D_LAST_PAYMENT_DATE_R,
		D_FIRST_PAYMENT_DATE_R,
		N_NO_OF_VOID_CHECKS_R,
		N_NO_OF_VOID_PAYMENTS_R,
		V_CLAIM_IDENTIFIER_R,
		N_CLAIM_SK_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		D_PRIOR_FISCAL_DATE,
		D_CURR_FISCAL_DATE,
		D_CYCLE_DATE_R,
		D_MAXRESERVAL_DATE_R
	)
	WITH RESERVE_PAYMENT_DTLS AS(
		SELECT
			D_PRIOR_FISCAL_DATE,
			D_CURR_FISCAL_DATE,
			D_CYCLE_DATE_R,
			D_MAXRESERVAL_DATE_R,
			SUM(FCPDRMV3.N_PAID_AMOUNT_R)										AS 			N_WAGE_BASE_R,
			SUM(
				CASE
					WHEN FCPDRMV3.N_PAID_AMOUNT_R IS NOT NULL THEN
						FCPDRMV3.N_PAID_AMOUNT_R * (FBPR.N_TAXABLE_PERCENT_R / 100)
					ELSE 0
				END
			) 																	AS			N_PAYMENT_TAXABLE_BENEFITS_R,
			SUM(
				CASE
					WHEN FCPDRMV3.N_PAID_AMOUNT_R IS NOT NULL THEN
						FCPDRMV3.N_PAID_AMOUNT_R * (1-FBPR.N_TAXABLE_PERCENT_R / 100)
					ELSE 0
				END
			) 																	AS			N_PAYMENT_NONTAXABLE_BEN_R,
			FBPR.N_TAXABLE_PERCENT_R,
			FBPR.N_NON_TAXABLE_BENEFITS_R,
			FBPR.N_MEDICARE_WAGE_BASE_R,
			FBPR.N_EMP_MEDICARE_WAGE_BASE_R,
			FBPR.N_EMP_FICA_WAGE_BASE_R,
			FBPDR.N_TAXABLE_BENEFITS_R,
			FBPDR.N_SIT_R,
			FBPDR.N_PAYMENT_DIRECT_AMT_R,
			FBPDR.N_MEDICARE_TAX_R,
			FBPDR.N_FUTA_R,
			FBPDR.N_FIT_R,
			FBPR.N_FICA_WAGE_BASE_R,
			FBPDR.N_FICA_R,
			FBPDR.N_EMPLOYER_MEDICARE_TAX_R,
			FBPDR.N_EMPLOYER_FICA_R,
			FCPDR.D_LAST_PAYMENT_TO_DATE_R,
			FCPDR.D_FIRST_PAYMENT_FROM_DATE_R,
			FLRDTLR.N_CURR_STAT_WV_DIRECT_AMT_R,
			FLRDTLR.N_CURR_GAAP_WV_DIRECT_AMT_R,
			FLRDTLR.N_CHG_STAT_WV_DIRECT_AMT_R,
			FLRDTLR.N_CHG_GAAP_WV_DIRECT_AMT_R,
			FCDR.D_LAST_PAYMENT_DATE_R,
			FCDR.D_FIRST_PAYMENT_DATE_R,
			VFCPDR.N_NO_OF_VOID_CHECKS_R,
			VFCPDR.N_NO_OF_VOID_PAYMENTS_R,
			DGCDRM.V_CLAIM_IDENTIFIER_R,
			DGCDRM.N_CLAIM_SK_R,
			DGCDRM.N_CLAIM_COVERAGE_SK_R,
			DGCDRM.N_CLAIM_COVERAGE_GROUP_SK_R
		FROM
			DIM_GRP_CLAIM_DETAIL_R_MV DGCDRM
		LEFT JOIN
		(
			SELECT
				V_CLAIM_IDENTIFIER_R,
				N_PAID_AMOUNT_R
			FROM
				FCT_CLAIM_PAYMENT_DETAIL_R_MV3
			WHERE
				V_BENEFIT_CODE_R NOT IN (
					'098',
					'097',
					'099',
					'200',
					'297',
					'298',
					'FIC',
					'MED'
				)
				AND N_FISCAL_MONTH_R = LTRIM(SUBSTR(P_N_BATCH_ID_R, 5, 2), 0)
				AND N_FISCAL_YEAR_R = SUBSTR(P_N_BATCH_ID_R, 1, 4)
		) FCPDRMV3
		ON
			FCPDRMV3.V_CLAIM_IDENTIFIER_R = DGCDRM.V_CLAIM_IDENTIFIER_R
		LEFT JOIN (
			SELECT
				N_CLAIM_SK_R,
				N_CLAIM_COVERAGE_GROUP_SK_R,
				MAX(N_TAXABLE_PERCENT_R)										AS 			N_TAXABLE_PERCENT_R,
				SUM(N_NONTAXABLE_BENEFIT_AMT_R)									AS			N_NON_TAXABLE_BENEFITS_R,
				SUM(N_EMPLOYEE_MED_WAGEBASE_AMT_R)								AS 			N_MEDICARE_WAGE_BASE_R,
				SUM(N_EMPLOYER_MED_WAGEBASE_AMT_R)								AS			N_EMP_MEDICARE_WAGE_BASE_R,
				SUM(N_EMPLOYEE_SS_WAGEBASE_AMT_R)								AS			N_FICA_WAGE_BASE_R,
				SUM(N_EMPLOYER_SS_WAGEBASE_AMT_R)								AS			N_EMP_FICA_WAGE_BASE_R
			FROM
				FCT_BENEFIT_PAYMENT_R
			WHERE
				EXTRACT(MONTH FROM D_PAYMENT_DATE_R) = EXTRACT(MONTH FROM D_CYCLE_DATE_R)
				AND EXTRACT(YEAR FROM D_PAYMENT_DATE_R) = EXTRACT(YEAR FROM D_CYCLE_DATE_R)
			GROUP BY
				N_CLAIM_SK_R,
				N_CLAIM_COVERAGE_GROUP_SK_R
		) FBPR
		ON
			FBPR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
			AND FBPR.N_CLAIM_COVERAGE_GROUP_SK_R = DGCDRM.N_CLAIM_COVERAGE_GROUP_SK_R
		LEFT JOIN (
			SELECT
				N_CLAIM_SK_R,
				N_CLAIM_COVERAGE_GROUP_SK_R,
				SUM(N_TAXABLE_BENEFIT_AMT_R)									AS			N_TAXABLE_BENEFITS_R,
				SUM(N_STATE_TAX_WITHHELD_AMT_R)									AS 			N_SIT_R,
				SUM(CASE WHEN N_AMOUNT_R IS NULL THEN 0 ELSE N_AMOUNT_R END)	AS			N_PAYMENT_DIRECT_AMT_R,
				SUM(N_EMPLOYEE_MED_WITHHELD_AMT_R)								AS			N_MEDICARE_TAX_R,
				SUM(
					CASE
						WHEN V_AMOUNT_TYPE_CODE_R IN ('097')
							THEN N_AMOUNT_R
						ELSE 0
					END
				)																AS			N_FUTA_R,
				SUM(N_FEDERAL_TAX_WITHHELD_AMT_R)								AS 			N_FIT_R,
				SUM(N_EMPLOYEE_SS_WITHHELD_AMT_R)								AS			N_FICA_R,
				SUM(N_EMPLOYER_MED_WITHHELD_AMT_R)								AS			N_EMPLOYER_MEDICARE_TAX_R,
				SUM(N_EMPLOYER_SS_WITHHELD_AMT_R)								AS			N_EMPLOYER_FICA_R
			FROM
				FCT_BENEFIT_PAYMENT_DETAIL_R
			WHERE
				EXTRACT(MONTH FROM D_PAYMENTDATE_R) = EXTRACT(MONTH FROM D_CYCLE_DATE_R)
				AND EXTRACT(YEAR FROM D_PAYMENTDATE_R) = EXTRACT(YEAR FROM D_CYCLE_DATE_R)
			GROUP BY
				N_CLAIM_SK_R,
				N_CLAIM_COVERAGE_GROUP_SK_R
		) FBPDR
		ON
			FBPDR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
			AND FBPDR.N_CLAIM_COVERAGE_GROUP_SK_R = DGCDRM.N_CLAIM_COVERAGE_GROUP_SK_R
		LEFT JOIN (
			SELECT /*+PARALLEL(8)*/
				FCPDTR.N_CLAIM_SK_R												AS 		N_CLAIM_SK_R,
				FCPDTR.N_CLAIM_COVERAGE_GROUP_SK_R								AS		N_CLAIM_COVERAGE_GROUP_SK_R,
				MAX(FCPDTR.D_SERVICE_PERIOD_TO_R)								AS		D_LAST_PAYMENT_TO_DATE_R,
				MIN(FCPDTR.D_SERVICE_PERIOD_FROM_R)								AS		D_FIRST_PAYMENT_FROM_DATE_R
			FROM
				FCT_CLAIM_PAYMENT_DETAIL_R FCPDTR
			JOIN
				DIM_TIME_R DTR
			ON
				FCPDTR.D_PAID_DATE_R = DTR.D_CALENDAR_DATE_R
			GROUP BY
				FCPDTR.N_CLAIM_SK_R,
				FCPDTR.N_CLAIM_COVERAGE_GROUP_SK_R
		) FCPDR
		ON
			FCPDR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
			AND FCPDR.N_CLAIM_COVERAGE_GROUP_SK_R = DGCDRM.N_CLAIM_COVERAGE_GROUP_SK_R
		LEFT JOIN (
			SELECT
				V_CLAIM_IDENTIFIER_R,
				V_COVERAGE_CODE_R,
				MAX(N_RESERVE_DIRECT__STAT__R) 									AS 			N_CURR_STAT_WV_DIRECT_AMT_R,
				MAX(N_RESERVE_DIRECT__GAAP__R)									AS 			N_CURR_GAAP_WV_DIRECT_AMT_R,
				MAX(N_CHG_RESERVE_DIRECT__STAT__R)								AS 			N_CHG_STAT_WV_DIRECT_AMT_R,
				MAX(N_CHG_RESERVE_DIRECT__GAAP__R)								AS			N_CHG_GAAP_WV_DIRECT_AMT_R
			FROM
				FCT_LG_RESERVE_DETAILS_R
			WHERE
				V_RESERVE_TYPE_IND_R = 'W'
				AND D_RESERVE_VALUATION_DATE_R = D_MAXRESERVAL_DATE_R
				AND V_CLAIM_IDENTIFIER_R IS NOT NULL
			GROUP BY
				V_CLAIM_IDENTIFIER_R,
				V_COVERAGE_CODE_R
		) FLRDTLR
		ON
			FLRDTLR.V_CLAIM_IDENTIFIER_R = DGCDRM.V_CLAIM_IDENTIFIER_R
			AND FLRDTLR.V_COVERAGE_CODE_R = DGCDRM.V_CLAIM_COVERAGE_CODE_R
		LEFT JOIN (
			SELECT
				N_CLAIM_SK_R,
				MAX(D_DISBURSE_DATE_R)											AS			D_LAST_PAYMENT_DATE_R,
				MIN(D_DISBURSE_DATE_R)											AS			D_FIRST_PAYMENT_DATE_R
			FROM
				FCT_CLAIM_DISBURSEMENT_R
			WHERE
				N_CLAIM_SK_R <> -1
			GROUP BY
				N_CLAIM_SK_R
		) FCDR
		ON
			FCDR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
		LEFT JOIN (
			SELECT
				VFCPDR_IN.V_CLAIM_IDENTIFIER_R,
				COUNT(1)														AS 		N_NO_OF_VOID_CHECKS_R,
				COUNT(1)														AS 		N_NO_OF_VOID_PAYMENTS_R
			FROM
			(
				SELECT
					D_SERVICE_PERIOD_FROM_R,
					V_CHECK_NUMBER_R,
					V_CLAIM_IDENTIFIER_R
				FROM
					FCT_CLAIM_PAYMENT_DETAIL_R_MV3
				WHERE
					N_FISCAL_MONTH_R = LTRIM(SUBSTR(P_N_BATCH_ID_R, 5, 2), 0)
					AND N_FISCAL_YEAR_R = SUBSTR(P_N_BATCH_ID_R, 1, 4)
					AND V_PAYMENT_STATUS_R = 'VOID'
			) VFCPDR_IN
			GROUP BY
				VFCPDR_IN.V_CLAIM_IDENTIFIER_R
		) VFCPDR
		ON
			VFCPDR.V_CLAIM_IDENTIFIER_R = DGCDRM.V_CLAIM_IDENTIFIER_R
		GROUP BY
            FBPR.N_NON_TAXABLE_BENEFITS_R,
            FBPR.N_MEDICARE_WAGE_BASE_R,
            FBPR.N_EMP_MEDICARE_WAGE_BASE_R,
            FBPR.N_EMP_FICA_WAGE_BASE_R,
            FBPDR.N_TAXABLE_BENEFITS_R,
            FBPDR.N_SIT_R,
            FBPDR.N_PAYMENT_DIRECT_AMT_R,
            FBPDR.N_MEDICARE_TAX_R,
            FBPDR.N_FUTA_R,
            FBPDR.N_FIT_R,
            FBPR.N_FICA_WAGE_BASE_R,
            FBPDR.N_FICA_R,
            FBPDR.N_EMPLOYER_MEDICARE_TAX_R,
            FBPDR.N_EMPLOYER_FICA_R,
            FCPDR.D_LAST_PAYMENT_TO_DATE_R,
            FCPDR.D_FIRST_PAYMENT_FROM_DATE_R,
            FLRDTLR.N_CURR_STAT_WV_DIRECT_AMT_R,
            FLRDTLR.N_CURR_GAAP_WV_DIRECT_AMT_R,
            FLRDTLR.N_CHG_STAT_WV_DIRECT_AMT_R,
            FLRDTLR.N_CHG_GAAP_WV_DIRECT_AMT_R,
            FCDR.D_LAST_PAYMENT_DATE_R,
            FCDR.D_FIRST_PAYMENT_DATE_R,
            VFCPDR.N_NO_OF_VOID_CHECKS_R,
            VFCPDR.N_NO_OF_VOID_PAYMENTS_R,
            DGCDRM.V_CLAIM_IDENTIFIER_R,
            DGCDRM.N_CLAIM_SK_R,
            DGCDRM.N_CLAIM_COVERAGE_SK_R,
            DGCDRM.N_CLAIM_COVERAGE_GROUP_SK_R,
            D_PRIOR_FISCAL_DATE,
            D_CURR_FISCAL_DATE,
            D_CYCLE_DATE_R,
            D_MAXRESERVAL_DATE_R,
            FBPR.N_TAXABLE_PERCENT_R
	)
	SELECT
		N_WAGE_BASE_R,
		N_PAYMENT_TAXABLE_BENEFITS_R,
		N_PAYMENT_NONTAXABLE_BEN_R,
		N_NON_TAXABLE_BENEFITS_R,
		N_MEDICARE_WAGE_BASE_R,
		N_EMP_MEDICARE_WAGE_BASE_R,
		N_EMP_FICA_WAGE_BASE_R,
		N_TAXABLE_BENEFITS_R,
		N_SIT_R,
		N_PAYMENT_DIRECT_AMT_R,
		N_MEDICARE_TAX_R,
		N_FUTA_R,
		N_FIT_R,
		N_FICA_WAGE_BASE_R,
		N_FICA_R,
		N_EMPLOYER_MEDICARE_TAX_R,
		N_EMPLOYER_FICA_R,
		D_LAST_PAYMENT_TO_DATE_R,
		D_FIRST_PAYMENT_FROM_DATE_R,
		N_CURR_STAT_WV_DIRECT_AMT_R,
		N_CURR_GAAP_WV_DIRECT_AMT_R,
		N_CHG_STAT_WV_DIRECT_AMT_R,
		N_CHG_GAAP_WV_DIRECT_AMT_R,
		D_LAST_PAYMENT_DATE_R,
		D_FIRST_PAYMENT_DATE_R,
		N_NO_OF_VOID_CHECKS_R,
		N_NO_OF_VOID_PAYMENTS_R,
		V_CLAIM_IDENTIFIER_R,
		N_CLAIM_SK_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		D_PRIOR_FISCAL_DATE,
		D_CURR_FISCAL_DATE,
		D_CYCLE_DATE_R,
		D_MAXRESERVAL_DATE_R
	FROM
		RESERVE_PAYMENT_DTLS;
	COMMIT;
EXCEPTION
WHEN OTHERS THEN
V_SQLERRM := SUBSTR(SQLERRM, 1, 4000);
	   RAISE_APPLICATION_ERROR(-20111, 'Raise Application Error in PRC_LOAD_STG_GRP_CLAIM_SUMMARY_PAYMENT_DETAILS_R :->' || V_SQLERRM);
END;

