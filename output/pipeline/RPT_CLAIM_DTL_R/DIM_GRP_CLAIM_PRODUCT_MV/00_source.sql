

  CREATE MATERIALIZED VIEW "ATOMIC"."DIM_GRP_CLAIM_PRODUCT_MV" ("RN", "N_PRODUCT_SK_R", "V_CLAIM_IDENTIFIER_R")
  SEGMENT CREATION IMMEDIATE
  ORGANIZATION HEAP PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255
 NOCOMPRESS LOGGING
  STORAGE(INITIAL 65536 NEXT 1048576 MINEXTENTS 1 MAXEXTENTS 2147483645
  PCTINCREASE 0 FREELISTS 1 FREELIST GROUPS 1
  BUFFER_POOL DEFAULT FLASH_CACHE DEFAULT CELL_FLASH_CACHE DEFAULT)
  TABLESPACE "OFS_OIDF_DATA_3"
  BUILD IMMEDIATE
  USING INDEX
  REFRESH FORCE ON DEMAND
  USING DEFAULT LOCAL ROLLBACK SEGMENT
  USING ENFORCED CONSTRAINTS DISABLE ON QUERY COMPUTATION DISABLE QUERY REWRITE
  AS SELECT rownum rn,
    n_product_sk_r,
    v_claim_identifier_r
  FROM
    --AS select rownum rn,n_product_sk_r,n_claim_sk_r from
    (
    SELECT n_product_sk_r,
      v_claim_identifier_r
      --n_product_sk_r,n_claim_sk_r
    FROM
      (SELECT NVL(D_GRP_PRODUCT_R_CLAIMS_LIFE.N_PRODUCT_SK_R, D_GRP_PRODUCT_R_CLAIMS_DISABILITY.N_PRODUCT_SK_R) N_PRODUCT_SK_R ,
        D_GRP_CLAIM_DIR_R_CLAIM.n_claim_sk_r,
        D_GRP_CLAIM_COVERAGE_GROUP_R_Claims.v_claim_identifier_r
      FROM DIM_GRP_CLAIM_COVERAGE_R D_GRP_CLAIM_COVERAGE_R_Claims
        -- D_GRP_CLAIM_COVERAGE_R_Claims
      LEFT OUTER JOIN MVW_PRODUCT_SK_LOOKUP T439745
        -- MVW_PRODUCT_SK_LOOKUP_For_Disablity
      ON D_GRP_CLAIM_COVERAGE_R_Claims.N_CLAIM_SK_R             = T439745.N_CLAIM_SK_R
      AND D_GRP_CLAIM_COVERAGE_R_Claims.V_CLAIM_COVERAGE_CODE_R = T439745.V_CLAIM_COVERAGE_CODE_R
      AND D_GRP_CLAIM_COVERAGE_R_Claims.n_claim_sk_r           <>-1
	  AND  D_GRP_CLAIM_COVERAGE_R_Claims.V_ACTIVE_STATUS_R                 = 'Y'
      LEFT OUTER JOIN DIM_GRP_PRODUCT_R D_GRP_PRODUCT_R_Claims_Disability
        -- D_GRP_PRODUCT_R_Claims_Disability
      ON D_GRP_PRODUCT_R_Claims_Disability.N_PRODUCT_SK_R     = T439745.N_PRODUCT_SK_R
      AND D_GRP_PRODUCT_R_Claims_Disability.V_ACTIVE_STATUS_R = 'Y'
      LEFT OUTER JOIN (SELECT * FROM DIM_GRP_CLAIM_COVERAGE_GROUP_R WHERE V_ACTIVE_STATUS_R= 'Y') D_GRP_CLAIM_COVERAGE_GROUP_R_Claims
      ON D_GRP_CLAIM_COVERAGE_GROUP_R_Claims.N_CLAIM_COVERAGE_SK_R = D_GRP_CLAIM_COVERAGE_R_Claims.N_CLAIM_COVERAGE_SK_R
      AND D_GRP_CLAIM_COVERAGE_GROUP_R_Claims.n_claim_sk_r        <>-1
      LEFT OUTER JOIN MVW_PRODUCT_SK_LOOKUP T439747
        -- MVW_PRODUCT_SK_LOOKUP_For_Life
      ON D_GRP_CLAIM_COVERAGE_GROUP_R_Claims.N_CLAIM_SK_R             = T439747.N_CLAIM_SK_R
      AND D_GRP_CLAIM_COVERAGE_GROUP_R_Claims.V_CLAIM_COVERAGE_CODE_R = T439747.V_CLAIM_COVERAGE_CODE_R
      LEFT OUTER JOIN DIM_GRP_PRODUCT_R D_GRP_PRODUCT_R_Claims_Life
        -- D_GRP_PRODUCT_R_Claims_Life
      ON D_GRP_PRODUCT_R_Claims_Life.N_PRODUCT_SK_R     = T439747.N_PRODUCT_SK_R
      AND D_GRP_PRODUCT_R_Claims_Life.V_ACTIVE_STATUS_R = 'Y',
        DIM_GRP_CLAIM_DIR_R D_GRP_CLAIM_DIR_R_Claim

      WHERE ( D_GRP_CLAIM_DIR_R_Claim.N_CLAIM_SK_R                        = D_GRP_CLAIM_COVERAGE_R_Claims.N_CLAIM_SK_R)
      AND D_GRP_CLAIM_DIR_R_Claim.V_ACTIVE_STATUS_R                       = 'Y'
      --AND D_GRP_CLAIM_COVERAGE_GROUP_R_Claims.V_ACTIVE_STATUS_R           = 'Y'
      --AND D_GRP_CLAIM_COVERAGE_R_Claims.V_ACTIVE_STATUS_R                 = 'Y'
      )
    GROUP BY N_PRODUCT_SK_R,
      v_claim_identifier_r
      --GROUP BY N_PRODUCT_SK_R,n_claim_sk_r
    )

