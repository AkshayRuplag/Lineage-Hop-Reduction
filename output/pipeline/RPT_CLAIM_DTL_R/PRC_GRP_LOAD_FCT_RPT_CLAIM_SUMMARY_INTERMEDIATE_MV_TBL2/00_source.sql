    /* Updated logic as of Sep 2024, based on discussion with John V */
    CLAIM_DECISION_DATE AS (
		SELECT DISTINCT
            CASE
            WHEN
                (NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) IN ('91', '92') AND
                        CPC.DD_CLAIM_FIRST_CLOSED_STAT_EFF_DATE IS NULL) --Error, they don't need Decision Date (Sep 2024)
                    THEN NULL
            ELSE
            COALESCE(
                    CPC.DD_CLAIM_FIRST_CLOSED_STAT_EFF_DATE,
                        CASE WHEN NVL(TRUNC(CPC.D_FIRST_BENEFIT_PAYMENT_DATE_R), TO_DATE('31-DEC-2999'))
                            < NVL(TRUNC(CPC.T_FIRST_OPEN_STATUS_EFF_DATE), TO_DATE('31-DEC-2999'))
                        THEN
                            TRUNC(CPC.D_FIRST_BENEFIT_PAYMENT_DATE_R)
                        ELSE
                            TRUNC(CPC.T_FIRST_OPEN_STATUS_EFF_DATE)
                        END
                )
			END										AS										D_CLAIM_DECISION_DATE_R,
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.V_CLAIM_NUMBER_R
			FROM (
