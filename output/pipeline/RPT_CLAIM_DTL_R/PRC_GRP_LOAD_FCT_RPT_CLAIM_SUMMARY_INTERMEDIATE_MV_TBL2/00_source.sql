

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ATOMIC"."PRC_GRP_LOAD_FCT_RPT_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL2"
(
	P_N_BATCH_ID_R		IN		NUMBER
)
AS
    V_SYS_DATE                	VARCHAR2(15) := TO_CHAR(SYSDATE, 'YYYYMMDDHHMISS');
	N_BATCH_ID_R				NUMBER 		 := P_N_BATCH_ID_R;
    N_MAX_SERIAL_NUM_R        	NUMBER;
    V_SQLCODE                 	VARCHAR2(100);
    V_SQLERRM                 	VARCHAR2(500);
	D_PRIOR_FISCAL_DATE 		DATE;
	D_CURR_FISCAL_DATE 			DATE;
	D_CYCLE_DATE_R 				DATE;
	D_MAXRESERVAL_DATE_R 		DATE;
BEGIN
	/* PRIOR FISC DATE */
	SELECT
        MAX(DTR.D_CALENDAR_DATE_R)
    INTO
        D_PRIOR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R < TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
            AND V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    ) DTR_PRIOR
    JOIN DIM_TIME_R DTR
    ON
        DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
        AND DTR.N_FISCAL_MONTH_R = DTR_PRIOR.N_FISCAL_MONTH_R
        AND DTR.N_FISCAL_YEAR_R = DTR_PRIOR.N_FISCAL_YEAR_R;

	/* CURRENT FISCAL DATE */
	SELECT
        DTR.D_CALENDAR_DATE_R
    INTO
        D_CURR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* CYCLE DATE */
    SELECT
        DTR.D_CALENDAR_DATE_R
    INTO
        D_CYCLE_DATE_R
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* TRUNCATE THE TABLE FIRST */
	EXECUTE IMMEDIATE 'TRUNCATE TABLE FCT_RPT_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL2 PURGE SNAPSHOT LOG';

	INSERT INTO FCT_RPT_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL2(
		N_CLAIM_SK_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		V_CLAIM_IDENTIFIER_R,
		V_CLAIM_NUMBER_R,
		N_CLAIM_AGE_R,
		V_CLAIM_ACTIVITY_DETAIL_R,
		D_CLAIM_DECISION_DATE_R,
		PRIOR_V_CLAIM_ACTIVITY_DET_R,
		PRIOR_V_CLAIM_ACTI_GROUP_R,
		CNT_V_CLAIM_IDENTIFIER_R,
		V_CLAIM_STATUS_R,
		V_PRIOR_CLOSED_CLAIM_DECISION_TYPE_R -- VB KPI:CLOSED CLAIM CHANGES

	)

	/* SECOND LEVEL INNER QUERY FUNCTIONS - CLAIM_SUMMARY_INTERMEDIATE_TBL2 */
	WITH CLAIM_AGE AS (
		SELECT
			DISTINCT
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			CASE
				WHEN DGCDR.V_LOB_TYPE_R IN ('LTD', 'STD', 'VPL', 'VPS')
					THEN
						CASE WHEN TO_NUMBER(TO_CHAR(NVL(DGCDTLR.D_CLOSURE_DATE_R, '01-JAN-2999'), 'YYYYMMDD')) <= 20230601 AND NVL(DGCDTLR.D_CLOSURE_DATE_R, '01-JAN-1900') >= SGCSR.D_RECEIVED_DATE_R
							THEN
								DGCDTLR.D_CLOSURE_DATE_R - SGCSR.D_RECEIVED_DATE_R
						ELSE
							TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD') - SGCSR.D_RECEIVED_DATE_R
						END
				WHEN DGCDR.V_LOB_TYPE_R IN ('LIFE', 'NONS', 'WOP')
					THEN
						CASE WHEN TO_NUMBER(TO_CHAR(NVL(DGCCGR.D_DATE_CLOSED_R, '01-JAN-2999'), 'YYYYMMDD')) <= 20230601 AND NVL(DGCCGR.D_DATE_CLOSED_R, '01-JAN-1900') >= SGCSR.D_RECEIVED_DATE_R --Bug Fix, 05-Nov-2021
							THEN
								DGCCGR.D_DATE_CLOSED_R - SGCSR.D_RECEIVED_DATE_R
						ELSE
							TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD') - SGCSR.D_RECEIVED_DATE_R
						END
			END 							AS				N_CLAIM_AGE_R
		FROM (
			SELECT
				*
			FROM
				STG_GRP_CLAIM_SUMMARY_R
			WHERE
				V_REASON_FLAG_R = 'Y'
		) SGCSR
		LEFT JOIN
			DIM_GRP_CLAIM_DIR_R DGCDR
		ON
			DGCDR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND DGCDR.V_ACTIVE_STATUS_R = 'Y'
			AND DGCDR.V_LOB_TYPE_R != 'ANNUITY'
		LEFT JOIN
			DIM_GRP_CLAIM_DETAIL_R DGCDTLR
		ON
			DGCDTLR.N_CLAIM_SK_R = COALESCE(DGCDR.N_CLAIM_SK_R, SGCSR.N_CLAIM_SK_R)
			AND DGCDTLR.V_ACTIVE_STATUS_R = 'Y'
		LEFT JOIN
			DIM_GRP_CLAIM_COVERAGE_GROUP_R DGCCGR
		ON
			DGCCGR.N_CLAIM_SK_R = COALESCE(DGCDR.N_CLAIM_SK_R, SGCSR.N_CLAIM_SK_R)
			AND DGCCGR.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
			AND DGCCGR.V_ACTIVE_STATUS_R = 'Y'
	),
	CLAIM_ACTIVITY_DETAIL AS (--current
		SELECT
			DISTINCT(
				CASE
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R = '1' and NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) = '35'
						THEN 'Approved (Extended Duration)'
                    --If it's Voluntary Benefits Claim, then if the status code is like 3% then it's an Open/Approved Claim (Nov 2024)
					WHEN (SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) LIKE '3%')
                        OR (SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) LIKE '3%' AND
                            DGPDR.V_POLICY_PREFIX_R IN ( 'VAI', 'VCI', 'VHI' ))
						OR (SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) ='73'
						    AND   DGPDR.V_POLICY_PREFIX_R IN ( 'VAI', 'VCI', 'VHI' )  AND UPPER(CD.V_COV_GRP_STATUS_R) = 'APPROVED')	---------08-10-25 changes
						THEN 'Approved'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) LIKE '41'
						THEN 'ASO Only'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) LIKE '42'
						THEN 'Closed - Other'
					-- Open Waivers
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_CLAIM_COVERAGE_CODE_R IN ( 'WP', 'IWP', 'WPS', 'BWP' ) AND SGCSR.V_REASON_CODE_R = '33'
						THEN 'Approved'
					-- Open Life
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_CLAIM_COVERAGE_CODE_R NOT IN ( 'WP', 'IWP', 'WPS', 'BWP' ) AND  SGCSR.N_CURR_GAAP_RESERVE_DIRECT_R > 0 AND SGCSR.V_REASON_CODE_R < '60'
						THEN 'Approved'
					-- Should this be Closed or Resisted?
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) = '51'
						THEN 'Resisted'
					-- Closed in Error
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) IN ( '91', '92' ) AND CSI.N_NO_OF_PAYMENTS_R = 0
						THEN 'Error'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_REASON_CODE_R in ( '91', '92' ) AND CSI.N_NO_OF_PAYMENTS_R = 0
						THEN 'Error'
					-- Special Close Types
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) IN ( '73', '65', '6F', '6G' )
						THEN 'Maximum Duration'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R in ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) IN ( '63' )
						THEN 'Any Occ'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R in ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) IN ( '66', '67' )
						THEN 'No Reply'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R in ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) IN ( '70' )
						 THEN 'Settlement'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R in ( '1', '2' ) AND NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) IN ( '72' )
						THEN 'Deceased'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_REASON_CODE_R IN ( '73') AND  DGPDR.V_POLICY_PREFIX_R IN ( 'VAI', 'VCI', 'VHI' )
                    AND UPPER(CD.V_COV_GRP_STATUS_R) <> 'APPROVED'---------08-10-25 changes
						THEN 'Maximum Duration'

					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_REASON_CODE_R IN ( '73', '65', '6F', '6G' )
						THEN 'Maximum Duration'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_REASON_CODE_R IN ( '63' )
						THEN 'Any Occ'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_REASON_CODE_R IN ( '66', '67' )
						THEN 'No Reply'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' ) AND SGCSR.V_REASON_CODE_R IN ( '70' )
						THEN 'Settlement'
					WHEN SGCSR.V_COVERAGE_TYPE_CODE_R IN ( '3' )
					  AND SGCSR.V_REASON_CODE_R in ( '72' )
					  THEN 'Deceased'
					-- Handle closed Disability
					when SGCSR.V_COVERAGE_TYPE_CODE_R in ( '1', '2' )
					  and NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R)             > '5Z'
					  and CSI.N_NO_OF_PAYMENTS_R                       = 0
					  then 'Denied'
				  when SGCSR.V_COVERAGE_TYPE_CODE_R in ( '1', '2' )
					  and NVL(SGCSR.V_REASON_CODE_R, SGCSR.V_CLAIM_STATUS_REASON_CODE_R)             > '5Z'
					  and CSI.N_NO_OF_PAYMENTS_R                       > 0
					  then 'Approved'
					-- Handle closed waivers
				  when SGCSR.V_COVERAGE_TYPE_CODE_R     in ( '3' )
					  and SGCSR.V_CLAIM_COVERAGE_CODE_R           in ( 'WP', 'IWP', 'WPS', 'BWP' )
					  and SGCSR.V_REASON_CODE_R > '5Z'
					  and CPC.T_FIRST_OPEN_STATUS_EFF_DATE                  is null
					  then 'Denied'
				  when SGCSR.V_COVERAGE_TYPE_CODE_R     in ( '3' )
					  and SGCSR.V_CLAIM_COVERAGE_CODE_R           in ( 'WP', 'IWP', 'WPS', 'BWP' )
					  and SGCSR.V_REASON_CODE_R > '5Z'
					  and CPC.T_FIRST_OPEN_STATUS_EFF_DATE                  is not null
					  then 'Approved'
					-- Handle closed life
				  when SGCSR.V_COVERAGE_TYPE_CODE_R     in ( '3' )
					  and SGCSR.V_REASON_CODE_R > '5Z'
					  and CSI.N_NO_OF_PAYMENTS_R                           = 0
					  then 'Denied'
				  when SGCSR.V_COVERAGE_TYPE_CODE_R     in ( '3' )
					  and SGCSR.V_REASON_CODE_R > '5Z'
					  and CSI.N_NO_OF_PAYMENTS_R                           > 0
					  then 'Approved'
				  when NVL(SGCSR.V_reason_code_r, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) like '5%' /* Was DIM_GRP_CLAIM_COVERAGE_GROUP_R.V_REASON_CODE_R */
					  then 'Resisted'
                  /*when SGCSR.V_COVERAGE_TYPE_CODE_R in ( 1, 2 ) and NVL(SGCSR.V_reason_code_r, SGCSR.V_CLAIM_STATUS_REASON_CODE_R) = '32'
                    then 'Reopened' --Added July 2024 as Reopened claim activity was not coming */
				  when SGCSR.V_REASON_CODE_R > '5Z'
				  then 'Closed - Other'
					-- Everything else should be pending
				  else 'Pending'
			end )								 AS 								V_CLAIM_ACTIVITY_DETAIL_R,
				SGCSR.N_CLAIM_SK_R,
				SGCSR.N_CLAIM_COVERAGE_SK_R,
				SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
				SGCSR.V_CLAIM_IDENTIFIER_R,
				SGCSR.V_CLAIM_NUMBER_R,
				CD.V_COV_GRP_STATUS_R AS V_CLAIM_STATUS_R---08-10-25 changes

			FROM (
				SELECT
					*
				FROM
					STG_GRP_CLAIM_SUMMARY_R
				WHERE
					V_REASON_FLAG_R = 'Y'
			) SGCSR
			LEFT JOIN
				--FCT_RPT_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL CPC
                FCT_RPT_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL CPC
			ON
				CPC.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
            /* Adding Policy Dir join to fetch policy Prefix (Nov 2024) */
            LEFT JOIN (
                SELECT
                    V_POLICY_NUMBER_R,
                    V_POLICY_PREFIX_R,
                    N_POLICY_SK_R
                FROM
                    DIM_GRP_POLICY_DIR_R
                WHERE
                    V_ACTIVE_STATUS_R = 'Y'
                    AND N_POLICY_SK_R <> -1
            ) DGPDR
            ON
                DGPDR.N_POLICY_SK_R = SGCSR.N_POLICY_SK_R
                AND DGPDR.V_POLICY_NUMBER_R = SGCSR.V_POLICY_NUMBER_R
			LEFT JOIN
				CLAIM_SUMMARY_INTERMEDIATE_MV_TBL CSI
			ON
				CSI.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
				LEFT JOIN ---------08-10-25 changes
				ATOMIC.DIM_GRP_CLAIM_COVERAGE_GROUP_R  CD
			ON CD.V_CLAIM_NUMBER_R = SGCSR.V_CLAIM_NUMBER_R
			AND CD.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
			AND CD.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
			AND CD.V_ACTIVE_STATUS_R ='Y'



	),
