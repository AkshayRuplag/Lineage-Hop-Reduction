

  CREATE MATERIALIZED VIEW "ATOMIC"."FCT_CLAIM_PAYMENT_DETAIL_R_PMNT_MV_SSL" ("V_CLAIM_NUMBER_R", "N_CLAIM_COVERAGE_GROUP_SK_R", "V_COV_GROUP_ID_R", "LAST_PAYMENT_DATE", "EARLIEST_PAYMENT_DATE", "MOST_RECENT_SERVICE_PERIOD_TO_DATE", "MOST_RECENT_SERVICE_PERIOD_FROM_DATE", "EARLIEST_SERVICE_PERIOD_TO_DATE", "EARLIEST_SERVICE_PERIOD_FROM_DATE")
  SEGMENT CREATION IMMEDIATE
  ORGANIZATION HEAP PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255
 NOCOMPRESS LOGGING
  STORAGE(INITIAL 65536 NEXT 8388608 MINEXTENTS 1 MAXEXTENTS 2147483645
  PCTINCREASE 0 FREELISTS 1 FREELIST GROUPS 1
  BUFFER_POOL DEFAULT FLASH_CACHE DEFAULT CELL_FLASH_CACHE DEFAULT)
  TABLESPACE "OFS_OIDF_DATA_3"
  PARALLEL 8
  BUILD IMMEDIATE
  USING INDEX
  REFRESH FORCE ON DEMAND
  USING DEFAULT LOCAL ROLLBACK SEGMENT
  USING ENFORCED CONSTRAINTS DISABLE ON QUERY COMPUTATION DISABLE QUERY REWRITE
  AS SELECT  v_claim_number_r ,  N_CLAIM_COVERAGE_GROUP_SK_R,
    V_COV_GROUP_ID_R,
     --MAX(d_paid_date_r) Last_Payment_Date, --07-Jun-2024 changes
    MAX(
        CASE
            WHEN N_PAID_AMOUNT_R > 0 THEN
                d_paid_date_r
        END
    )                                last_payment_date,--07-Jun-2024 changes
	 min(d_paid_date_r) earliest_payment_date,
     max(D_SERVICE_PERIOD_TO_R) MOST_RECENT_SERVICE_PERIOD_TO_DATE,
     max(D_SERVICE_PERIOD_FROM_R) MOST_RECENT_SERVICE_PERIOD_FROM_DATE,
     min(D_SERVICE_PERIOD_TO_R)   EARLIEST_SERVICE_PERIOD_TO_DATE,
     min(D_SERVICE_PERIOD_FROM_R) EARLIEST_SERVICE_PERIOD_FROM_DATE
  FROM
    (SELECT   v_claim_number_r,
      d_paid_date_r,
      N_SOURCE_VERSION_SEQ_NUMBER_R,
      SUM(N_PAID_AMOUNT_R) N_PAID_AMOUNT_R,
      N_CLAIM_COVERAGE_GROUP_SK_R,
      V_COV_GROUP_ID_R,
     D_SERVICE_PERIOD_FROM_R,
      D_SERVICE_PERIOD_TO_R
    FROM fct_claim_payment_detail_r_MV_SSL
    WHERE V_CHECK_TYPE_R      <> 'OE'
    AND V_BENEFIT_GROUP_R NOT IN ('FIC', 'MED')
    GROUP BY v_claim_number_r,
      d_paid_date_r,
      N_SOURCE_VERSION_SEQ_NUMBER_R,
      N_CLAIM_COVERAGE_GROUP_SK_R,
      V_COV_GROUP_ID_R,
      D_SERVICE_PERIOD_FROM_R,
      D_SERVICE_PERIOD_TO_R
    --HAVING SUM(N_PAID_AMOUNT_R) >0--24-mAY-2024 CHANGES
    HAVING SUM(N_PAID_AMOUNT_R) <>0 --24-mAY-2024 CHANGES
    )
  GROUP BY v_claim_number_r,
    N_CLAIM_COVERAGE_GROUP_SK_R,
    V_COV_GROUP_ID_R

