    BEGIN
      SELECT 
        DTR.D_CALENDAR_DATE_R 
    INTO
        D_CURR_FISCAL_DATE
    FROM
    (
        SELECT 
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R 
        FROM
            DIM_TIME_R 
        WHERE 
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
