create or replace PROCEDURE PRC_GRP_LOAD_MERGE_UPDATE_FCT_CLAIM_PAYMENT_REINS_R (
	P_BATCH_ID_R IN NUMBER
)  AS
	V_SYS_DATE          VARCHAR2(15) := TO_CHAR(SYSDATE,'YYYYMMDDHHMISS');
	N_MAX_SERIAL_NUM_R  NUMBER;
	V_SQLCODE           VARCHAR2(100);
	V_SQLERRM           VARCHAR2(500);
	LN_BATCH_ID_R       NUMBER       := P_BATCH_ID_R;
    D_PRIOR_FISCAL_DATE DATE;
    D_CURR_FISCAL_DATE  DATE;

    -- Suresh 19/02/2025 Add merge condition for FCT_BENEFIT_PAYMENT_DETAIL_OFFSET_MV_TBL only for benifit code 080.
    -- Suresh 21/02/2025 Replace P_BATCH_ID_R to TO_NUMBER(TO_CHAR(SYSDATE-1,'YYYYMMDD') ||'0000') Line no 52.
    -- Suresh 24/02/2025 Add Exception handling.

BEGIN

    /* PRIOR FISC DATE */
  BEGIN
	SELECT 
        MAX(DTR.D_CALENDAR_DATE_R)
    INTO
        D_PRIOR_FISCAL_DATE
    FROM
    (
        SELECT 
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R 
        FROM
            DIM_TIME_R 
        WHERE 
            D_CALENDAR_DATE_R < TO_DATE(SUBSTR(P_BATCH_ID_R, 1, 8), 'YYYYMMDD')
            AND V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    ) DTR_PRIOR
    JOIN DIM_TIME_R DTR
    ON
        DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
        AND DTR.N_FISCAL_MONTH_R = DTR_PRIOR.N_FISCAL_MONTH_R
        AND DTR.N_FISCAL_YEAR_R = DTR_PRIOR.N_FISCAL_YEAR_R;   
  EXCEPTION WHEN OTHERS THEN   --24-02-2025 EXCEPTION HANDING ADDED  
    SELECT 
        MAX(DTR.D_CALENDAR_DATE_R)
    INTO
        D_PRIOR_FISCAL_DATE
    FROM
    (
        SELECT 
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R 
        FROM
            DIM_TIME_R 
        WHERE 
            D_CALENDAR_DATE_R < TO_DATE(SUBSTR(TO_NUMBER(TO_CHAR(SYSDATE-1,'YYYYMMDD') ||'0000'), 1, 8), 'YYYYMMDD')
            AND V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    ) DTR_PRIOR
    JOIN DIM_TIME_R DTR
    ON
        DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
        AND DTR.N_FISCAL_MONTH_R = DTR_PRIOR.N_FISCAL_MONTH_R
        AND DTR.N_FISCAL_YEAR_R = DTR_PRIOR.N_FISCAL_YEAR_R;
  END;
