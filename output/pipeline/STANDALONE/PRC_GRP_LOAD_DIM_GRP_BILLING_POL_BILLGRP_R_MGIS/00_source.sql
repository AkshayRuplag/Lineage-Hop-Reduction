

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ATOMIC"."PRC_GRP_LOAD_DIM_GRP_BILLING_POL_BILLGRP_R_MGIS"


AS
BEGIN

DELETE from ATOMIC.DIM_GRP_BILLING_POL_BILLGRP_R where V_SOURCE_SYSTEM_NAME_R = 'MGIS';
commit;

    -- Insert data into the target Insert into
 INSERT INTO ATOMIC.DIM_GRP_BILLING_POL_BILLGRP_R
(
N_POLICY_BILLGROUP_ID_R,
N_POLICY_BILLGROUP_SK_R ,
V_SOURCE_SYSTEM_NAME_R ,
N_POLICY_SK_R  ,
FIC_MIS_DATE_R ,
N_BATCH_ID_R  ,
N_SEQUENCE_NUMBER_R ,
T_CREATION_DATE_R ,
T_LAST_MODIFIED_DATE_R ,
V_CREATED_BY_R   ,
V_LAST_MODIFIED_BY_R,
V_ACTIVE_STATUS_R
)
SELECT
A.N_BILL_GROUP_R AS N_POLICY_BILLGROUP_ID_R,
(select NVL(MAX(N_POLICY_BILLGROUP_SK_R),0) from ATOMIC.DIM_GRP_BILLING_POL_BILLGRP_R) + rownum as N_POLICY_BILLGROUP_SK_R ,
'MGIS' AS V_SOURCE_SYSTEM_NAME_R ,
C.N_POLICY_SK_R  ,
sysdate as FIC_MIS_DATE_R ,
TO_NUMBER(TO_CHAR(SYSDATE,'YYYYDD'))||'0000' as N_BATCH_ID_R  ,
(select NVL(MAX(N_SEQUENCE_NUMBER_R),0) from ATOMIC.DIM_GRP_BILLING_POL_BILLGRP_R) + rownum as N_SEQUENCE_NUMBER_R ,
sysdate as T_CREATION_DATE_R,
sysdate as T_LAST_MODIFIED_DATE_R,
'Data Lake' as V_CREATED_BY_R,
'Data Lake' as V_LAST_MODIFIED_BY_R,
'Y' AS V_ACTIVE_STATUS_R
FROM
(Select distinct
 V_PREFIX_R,N_SUFFIX_R,
 N_BILL_GROUP_R


FROM
STG_MGIS_RM_PREMIUM_R ) A
INNER JOIN
dim_grp_policy_dir_r C
ON
A.V_PREFIX_R||A.N_SUFFIX_R = C.V_ORIG_POLICY_NUMBER_R
AND C.V_ACTIVE_STATUS_R='Y'
WHERE
NOT EXISTS ( Select 1 from DIM_GRP_BILLING_POL_BILLGRP_R D WHERE A.N_BILL_GROUP_R = D.N_POLICY_BILLGROUP_ID_R
            AND C.N_POLICY_SK_R = D.N_POLICY_SK_R AND D.V_SOURCE_SYSTEM_NAME_R = 'MGIS') ;
commit;
END;

