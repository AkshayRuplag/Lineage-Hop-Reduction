

  CREATE MATERIALIZED VIEW "ATOMIC"."RPT_CLAIM_DTL_R_TOTBENPERDYS_MV_SSL" ("V_CLAIM_NUMBER_R", "N_TOTAL_BENEFIT_PERIOD_DAYS_R")
  SEGMENT CREATION IMMEDIATE
  ORGANIZATION HEAP PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255
 NOCOMPRESS LOGGING
  STORAGE(INITIAL 65536 NEXT 1048576 MINEXTENTS 1 MAXEXTENTS 2147483645
  PCTINCREASE 0 FREELISTS 1 FREELIST GROUPS 1
  BUFFER_POOL DEFAULT FLASH_CACHE DEFAULT CELL_FLASH_CACHE DEFAULT)
  TABLESPACE "OFS_OIDF_DATA_3"
  BUILD IMMEDIATE
  USING INDEX
  REFRESH FORCE ON DEMAND
  USING DEFAULT LOCAL ROLLBACK SEGMENT
  USING ENFORCED CONSTRAINTS DISABLE ON QUERY COMPUTATION DISABLE QUERY REWRITE
  AS SELECT v_claim_number_r, SUM(Differ) as n_total_benefit_period_days_r FROM (
select /*+PARALLEL(4)*/
  --d_paid_date_r,
  v_claim_number_r,D_SERVICE_PERIOD_FROM_R,D_SERVICE_PERIOD_TO_R,
D_SERVICE_PERIOD_TO_R-D_SERVICE_PERIOD_FROM_R as Differ
--,case when V_PAYMENT_STATUS_R <> 'VOID' then (D_SERVICE_PERIOD_TO_R-D_SERVICE_PERIOD_FROM_R) else -1*(D_SERVICE_PERIOD_TO_R-D_SERVICE_PERIOD_FROM_R) end as Differ
from fct_claim_payment_detail_r_mv_ssl fct_claim_payment_detail_r
where
-- V_CLAIM_NUMBER_R in ('2022-12-23-0067-NYPL-01') and
(D_PAID_DATE_R) <= (select to_date(to_char(D_EDS_CYCLEDATE_R,'dd-mon-yyyy'))
from PRCS_GRP_DATE_PARAM_R
where V_PROCESS_NAME_R ='PACS_BATCH_ID')
GROUP BY
V_CLAIM_NUMBER_R,D_SERVICE_PERIOD_FROM_R,D_SERVICE_PERIOD_TO_R)
GROUP BY v_claim_number_r

