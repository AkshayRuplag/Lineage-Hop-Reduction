

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ATOMIC"."PRC_LOAD_STG_GRP_CLAIM_SUMMARY_COVRG_TIER_TBL_R"
(
	P_N_BATCH_ID_R		IN		NUMBER
)
AS
    V_SYS_DATE                	VARCHAR2(15) := TO_CHAR(SYSDATE, 'YYYYMMDDHHMISS');
	N_BATCH_ID_R				NUMBER 		 := P_N_BATCH_ID_R;
    N_MAX_SERIAL_NUM_R        	NUMBER;
    V_SQLCODE                 	VARCHAR2(100);
    V_SQLERRM                 	VARCHAR2(500);
	D_PRIOR_FISCAL_DATE 		DATE;
	D_CURR_FISCAL_DATE 			DATE;
	D_CYCLE_DATE_R 				DATE;
	D_MAXRESERVAL_DATE_R 		DATE;
BEGIN
	/* PRIOR FISC DATE */
	SELECT
        MAX(DTR.D_CALENDAR_DATE_R)
    INTO
        D_PRIOR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R < TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
            AND V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    ) DTR_PRIOR
    JOIN DIM_TIME_R DTR
    ON
        DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
        AND DTR.N_FISCAL_MONTH_R = DTR_PRIOR.N_FISCAL_MONTH_R
        AND DTR.N_FISCAL_YEAR_R = DTR_PRIOR.N_FISCAL_YEAR_R;

	/* CURRENT FISCAL DATE */
	SELECT
		DTR.D_CALENDAR_DATE_R
    INTO
		D_CURR_FISCAL_DATE
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* CYCLE DATE */
    SELECT
		DTR.D_CALENDAR_DATE_R
    INTO
		D_CYCLE_DATE_R
    FROM
    (
        SELECT
            N_FISCAL_MONTH_R,
            N_FISCAL_YEAR_R
        FROM
            DIM_TIME_R
        WHERE
            D_CALENDAR_DATE_R = TO_DATE(SUBSTR(P_N_BATCH_ID_R, 1, 8), 'YYYYMMDD')
    ) DTR_CURR
    JOIN DIM_TIME_R DTR
    ON
    DTR.V_END_OF_FISCAL_MONTH_IND_R = 'Y'
    AND DTR.N_FISCAL_MONTH_R = DTR_CURR.N_FISCAL_MONTH_R
    AND DTR.N_FISCAL_YEAR_R = DTR_CURR.N_FISCAL_YEAR_R;

	/* TRUNCATE THE TABLE FIRST */
	EXECUTE IMMEDIATE 'TRUNCATE TABLE STG_GRP_CLAIM_SUMMARY_COVRG_TIER_R PURGE SNAPSHOT LOG';
	INSERT INTO STG_GRP_CLAIM_SUMMARY_COVRG_TIER_R(
		N_CLAIM_SK_R,
		V_CLAIM_STATUS_REASON_CODE_R,
		V_REASON_CODE_R,
		T_EVENT_TIMESTAMP_R_1,
		T_EVENT_TIMESTAMP_R_2,
		V_REASON_FLAG_R,
		V_CLAIM_NUMBER_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		V_CLAIM_IDENTIFIER_R,
		V_CLAIM_COVERAGE_CODE_R,
		V_COVERAGE_TYPE_CODE_R,
		N_CUST_PARTY_SK_R,
		N_PARTY_SK_R,
		N_POLICY_SK_R,
		V_POLICY_NUMBER_R,
		V_POLICY_PREFIX_R,
		V_POLICY_SUFFIX_R,
		N_TIER_NUM_R,
		V_WFAM_CODE_R,
		D_POTENTIAL_RESOLUTION_DATE_R,
		V_TIER_DESCRIPTION_R,
		V_RECOVERY_EXPECTATIONS_R,
		V_CLINICAL_VOC_ENGAGEMENT_R,
		V_ACCOMMODATIONS_NEEDED_R,
		N_LTD_APPROVED_CLMS_ANY_OCC_R,
		N_LTD_APPROVED_CLMS_OWN_OCC_R,
		N_LTD_APPRVED_OWNOCC_FULLDUR_R,
		V_LTD_ANY_OCC_GROUP_R,
		V_SS_PURSUE_INDICATED_R,
		V_CLAIMS_BRIDGED_STD_TO_LTD_R,
		N_OVERPAYMENT_BALANCE_R,
		D_RECEIVED_DATE_R,
		D_CLOSURE_DATE_R
	)
	SELECT DISTINCT
		N_CLAIM_SK_R,
		V_CLAIM_STATUS_REASON_CODE_R,
		V_REASON_CODE_R,
		T_EVENT_TIMESTAMP_R_1,
		T_EVENT_TIMESTAMP_R_2,
		V_REASON_FLAG_R,
		V_CLAIM_NUMBER_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		V_CLAIM_IDENTIFIER_R,
		V_CLAIM_COVERAGE_CODE_R,
		V_COVERAGE_TYPE_CODE_R,
		N_CUST_PARTY_SK_R,
		N_PARTY_SK_R,
		N_POLICY_SK_R,
		V_POLICY_NUMBER_R,
		V_POLICY_PREFIX_R,
		V_POLICY_SUFFIX_R,
		N_TIER_NUM_R,
		V_WFAM_CODE_R,
		D_POTENTIAL_RESOLUTION_DATE_R,
		V_TIER_DESCRIPTION_R,
		V_RECOVERY_EXPECTATIONS_R,
		V_CLINICAL_VOC_ENGAGEMENT_R,
		V_ACCOMMODATIONS_NEEDED_R,
		N_LTD_APPROVED_CLMS_ANY_OCC_R,
		N_LTD_APPROVED_CLMS_OWN_OCC_R,
		N_LTD_APPRVED_OWNOCC_FULLDUR_R,
		V_LTD_ANY_OCC_GROUP_R,
		V_SS_PURSUE_INDICATED_R,
		V_CLAIMS_BRIDGED_STD_TO_LTD_R,
		N_OVERPAYMENT_BALANCE_R,
		D_RECEIVED_DATE_R,
		D_CLOSURE_DATE_R
	FROM (
		WITH CLAIM_DTLS AS (
			SELECT
				DGCDRM.N_CLAIM_SK_R,
				DGCDRM.V_CLAIM_STATUS_REASON_CODE_R,
				DGCDRM.V_REASON_CODE_R,
				DGCDRM.T_EVENT_TIMESTAMP_R_1,
				DGCDRM.T_EVENT_TIMESTAMP_R_2,
				DGCDRM.V_REASON_FLAG_R,
				DGCDRM.V_CLAIM_NUMBER_R,
				DGCDRM.N_CLAIM_COVERAGE_SK_R,
				DGCDRM.N_CLAIM_COVERAGE_GROUP_SK_R,
				DGCDRM.V_CLAIM_IDENTIFIER_R,
				DGCDRM.V_CLAIM_COVERAGE_CODE_R,
				DGPR.V_COVERAGE_TYPE_CODE_R,
				FGPR.N_CUST_PARTY_SK_R,
				DGPTYR.N_PARTY_SK_R,
				DGCDRM.N_POLICY_SK_R,
				DGCDRM.V_POLICY_NUMBER_R,
				FGCNR.N_TIER_NUM_R,
				FGCNR.V_WFAM_CODE_R,
				FGCNR.D_POTENTIAL_RESOLUTION_DATE_R,
				DGRTR.V_TIER_DESCRIPTION_R,
				DGRTR.V_RECOVERY_EXPECTATIONS_R,
				DGRTR.V_CLINICAL_VOC_ENGAGEMENT_R,
				DGRTR.V_ACCOMMODATIONS_NEEDED_R,
				DGPDR.V_POLICY_PREFIX_R,
				DGPDR.V_POLICY_SUFFIX_R,
				CASE
					WHEN DGCER.ANY_OCC_GROUP = 'Any Occ'
						THEN 'Y'
						ELSE NULL
				END											AS 			N_LTD_APPROVED_CLMS_ANY_OCC_R,
				CASE
					WHEN DGCER.ANY_OCC_GROUP = 'Own Occ'
						THEN 'Y'
					ELSE NULL
				END 										AS 			N_LTD_APPROVED_CLMS_OWN_OCC_R,
				CASE
					WHEN DGCER.ANY_OCC_GROUP = 'Own Occ Only'
						THEN 'Y'
					ELSE NULL
				END 										AS 			N_LTD_APPRVED_OWNOCC_FULLDUR_R,
				CASE
					WHEN DGCER.ANY_OCC_GROUP = 'Own Occ Only'
						THEN DGCER.ANY_OCC_GROUP
					WHEN TRUNC(D_CURR_FISCAL_DATE) <= TRUNC(DGCER.D_ANYOCC_START_DATE_R)
						THEN 'Own Occ'
					ELSE 'Any Occ'
				END 										AS 				V_LTD_ANY_OCC_GROUP_R,
				V_SS_PURSUE_FLAG_R 							AS 				V_SS_PURSUE_INDICATED_R,
				FCAR.N_OVERPAYMENT_BALANCE_R				AS				N_OVERPAYMENT_BALANCE_R,
				DGCDTLR.D_CLOSURE_DATE_R
				FROM
					dim_grp_claim_detail_r_MV DGCDRM
				JOIN
					(
					SELECT
						MVW_PRODUCT_SK_LOOKUP_TBL.N_CLAIM_SK_R,
						DIM_GRP_PRODUCT_R.V_COVERAGE_TYPE_CODE_R
					FROM
						DIM_GRP_PRODUCT_R
					JOIN
						MVW_PRODUCT_SK_LOOKUP_TBL
					ON
						DIM_GRP_PRODUCT_R.N_PRODUCT_SK_R = MVW_PRODUCT_SK_LOOKUP_TBL.N_PRODUCT_SK_R
					WHERE
						DIM_GRP_PRODUCT_R.V_COVERAGE_CATEGORY_R <> 'Life - Annuity'
						AND DIM_GRP_PRODUCT_R.V_COVERAGE_CODE_R <> 'ORL' --Added in because ORL claims are not required as confirmed by John (July 2024)
				) DGPR
				ON
					DGPR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
				JOIN (
					SELECT
						N_CLAIM_SK_R,
						N_INSRD_PARTY_SK_R,
						D_CLOSURE_DATE_R
					FROM
						DIM_GRP_CLAIM_DETAIL_R
					WHERE
						V_ACTIVE_STATUS_R = 'Y'
				) DGCDTLR
				ON
					DGCDTLR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
				-- If the policy information is not present in Claim table, it should not get lost
				-- So, changed to LEFT JOIN (Apr 2024)
				-- Added below for CUST PARTY SK
				LEFT JOIN
					DIM_GRP_POLICY_DIR_R DGPDR
				ON
					DGPDR.V_ACTIVE_STATUS_R = 'Y'
					AND DGPDR.N_POLICY_SK_R = DGCDRM.N_POLICY_SK_R
				LEFT JOIN (
					SELECT
						MAX(N_CUST_PARTY_SK_R)              AS              N_CUST_PARTY_SK_R,
						N_POLICY_SK_R,
						N_VERSION_NUMBER_R
					FROM
						FCT_GRP_POLICY_R
					GROUP BY
						N_POLICY_SK_R,
						N_VERSION_NUMBER_R
				) FGPR
				ON
					FGPR.N_POLICY_SK_R = DGPDR.N_POLICY_SK_R
					AND FGPR.N_VERSION_NUMBER_R = DGPDR.N_POLICY_VERSION_NUMBER_R
				LEFT JOIN (
					SELECT
						N_PARTY_SK_R,
						V_PARTY_TYPE_R
					FROM
						DIM_GRP_PARTY_DIR_R
					WHERE
						V_ACTIVE_STATUS_R = 'Y'
				) DGPTYR
				ON
					DGPTYR.N_PARTY_SK_R = DGCDTLR.N_INSRD_PARTY_SK_R
				LEFT JOIN (
					SELECT
						N_TIER_NUM_R,
						V_WFAM_CODE_R,
						D_POTENTIAL_RESOLUTION_DATE_R,
						N_CLAIM_SK_R,
						RNK
					FROM (
						SELECT
							TO_NUMBER(SUBSTR(V_TIER_R, 6)) AS N_TIER_NUM_R,
							V_WFAM_R AS V_WFAM_CODE_R ,
							D_PRD_R AS D_POTENTIAL_RESOLUTION_DATE_R,
							T_EVENT_TIMESTAMP_R,
							N_CLAIM_SUBSEQUENCE_NUMBER_R,
							N_SEQ_R,
							N_CLAIM_SK_R,
							RANK() OVER(
								PARTITION BY N_CLAIM_SK_R
								ORDER BY
									T_EVENT_TIMESTAMP_R DESC,
									N_SEQ_R DESC,
									N_CLAIM_SUBSEQUENCE_NUMBER_R DESC
							) RNK
						FROM (
							SELECT
								*
							FROM
								FCT_GRP_CLAIM_NOTE_R
							WHERE
								N_CLAIM_SK_R <> -1
								AND V_TIER_R IS NOT NULL /*Does not consider Tier NULL, may need to revisit based on User review (2023)*/
							) CLM_NOTE_INNER
					) CLM_NOTE_OUTER
					WHERE RNK = 1
				) FGCNR
				ON
					FGCNR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
				LEFT JOIN (
					SELECT
						V_TIER_DESCRIPTION_R,
						V_COVERAGE_TYPE_CODE_R,
						N_TIER_NUM_R,
						V_RECOVERY_EXPECTATIONS_R,
						V_CLINICAL_VOC_ENGAGEMENT_R,
						V_ACCOMMODATIONS_NEEDED_R
					FROM
						DIM_GRP_REF_TIER_R
					WHERE
						V_ACTIVE_STATUS_R = 'Y'
				) DGRTR
				ON
					DGRTR.V_COVERAGE_TYPE_CODE_R = DGPR.V_COVERAGE_TYPE_CODE_R
					AND DGRTR.N_TIER_NUM_R = FGCNR.N_TIER_NUM_R
				LEFT JOIN (
					SELECT CASE
						WHEN ANY_OCC_INDICATOR = 'A'
							THEN 'Own Occ Only'
						WHEN TRUNC(D_CURR_FISCAL_DATE) <= TRUNC(D_ANYOCC_START_DATE_R)
							THEN 'Own Occ'
						WHEN TRUNC(D_CURR_FISCAL_DATE) > TRUNC(D_ANYOCC_START_DATE_R)
							THEN 'Any Occ'
						ELSE 'Unknown'
						END 		AS           ANY_OCC_GROUP,
						N_CLAIM_SK_R,
						D_ANYOCC_START_DATE_R
					FROM (
						SELECT CASE
							WHEN UPPER(V_OWN_OCC_PERIOD_R) LIKE '%MOS'
								THEN 'M'
							WHEN V_OWN_OCC_PERIOD_R LIKE '@%'
								THEN 'A'
							END AS ANY_OCC_INDICATOR,
							D_ANYOCC_START_DATE_R,
							N_CLAIM_SK_R
						FROM
							DIM_GRP_CLAIM_ELIGIBILITY_R
						WHERE
							V_ACTIVE_STATUS_R = 'Y'
					) DGCER_INNER
				) DGCER
				ON
					DGCER.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
				LEFT JOIN (
					SELECT
						CASE
							WHEN UPPER(V_SS_PURSUE_FLAG_R) = 'YES'
								THEN 'Y'
							WHEN UPPER(V_SS_PURSUE_FLAG_R) = 'NO'
								THEN 'N'
							WHEN UPPER(V_SS_PURSUE_FLAG_R) = 'INSURED PURSUING'
								THEN 'I'
							ELSE V_SS_PURSUE_FLAG_R
						END             AS      V_SS_PURSUE_FLAG_R,
						N_CLAIM_SK_R
					FROM
						FCT_CLAIM_SOCIALSECURITY_INC_R
					WHERE
						N_CLAIM_SK_R <> -1
				) FCSSIR
				ON
					FCSSIR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
				LEFT JOIN (
					SELECT
						N_CLAIM_SK_R,
						SUM(
							CASE
								WHEN UPPER(V_ADJUSTMENT_DESC_R) LIKE 'TNRFR%' THEN NULL
								ELSE
									CASE
										WHEN N_DR_INDICATOR_R = 1 THEN N_ADJ_TRANS_AMOUNT_R
										WHEN N_DR_INDICATOR_R = 0 THEN (-1 * N_ADJ_TRANS_AMOUNT_R)
									END
							END
						)								AS		N_OVERPAYMENT_BALANCE_R
					FROM
						FCT_CLAIM_ADJUSTMENT_R
					WHERE
						N_CLAIM_SK_R <> -1
					GROUP BY
						N_CLAIM_SK_R
				) FCAR
				ON
					FCAR.N_CLAIM_SK_R = DGCDRM.N_CLAIM_SK_R
		),
		STD_TO_LTD_BRIDGE_CLAIMS AS (
			SELECT
				CDTLS.N_CLAIM_SK_R,
				CDTLS.V_CLAIM_STATUS_REASON_CODE_R,
				CDTLS.V_REASON_CODE_R,
				CDTLS.T_EVENT_TIMESTAMP_R_1,
				CDTLS.T_EVENT_TIMESTAMP_R_2,
				CDTLS.V_REASON_FLAG_R,
				CDTLS.V_CLAIM_NUMBER_R,
				CDTLS.N_CLAIM_COVERAGE_SK_R,
				CDTLS.N_CLAIM_COVERAGE_GROUP_SK_R,
				CDTLS.V_CLAIM_IDENTIFIER_R,
				CDTLS.V_CLAIM_COVERAGE_CODE_R,
				CDTLS.V_COVERAGE_TYPE_CODE_R,
				CDTLS.N_CUST_PARTY_SK_R,
				CDTLS.N_PARTY_SK_R,
				CDTLS.N_POLICY_SK_R,
				CDTLS.V_POLICY_NUMBER_R,
				CDTLS.V_POLICY_PREFIX_R,
				CDTLS.V_POLICY_SUFFIX_R,
				CDTLS.N_TIER_NUM_R,
				CDTLS.V_WFAM_CODE_R,
				CDTLS.D_POTENTIAL_RESOLUTION_DATE_R,
				CDTLS.V_TIER_DESCRIPTION_R,
				CDTLS.V_RECOVERY_EXPECTATIONS_R,
				CDTLS.V_CLINICAL_VOC_ENGAGEMENT_R,
				CDTLS.V_ACCOMMODATIONS_NEEDED_R,
				CDTLS.N_LTD_APPROVED_CLMS_ANY_OCC_R,
				CDTLS.N_LTD_APPROVED_CLMS_OWN_OCC_R,
				CDTLS.N_LTD_APPRVED_OWNOCC_FULLDUR_R,
				CDTLS.V_LTD_ANY_OCC_GROUP_R,
				CDTLS.V_SS_PURSUE_INDICATED_R,
				CDTLS.N_OVERPAYMENT_BALANCE_R,
				CASE
					WHEN CLM_PRD.N_CLAIM_SK_R IS NOT NULL
						THEN 'Has LTD'
					ELSE NULL
				END 																		AS			V_CLAIMS_BRIDGED_STD_TO_LTD_R,
				COALESCE(
					DGBOR.D_AUDIT_DATE_R,
					CASE
						WHEN REGEXP_LIKE(CDTLS.V_CLAIM_NUMBER_R, '^\d{4}-\d{2}-\d{2}\S*')
							THEN TO_DATE(SUBSTR(CDTLS.V_CLAIM_NUMBER_R, 1, 10), 'YYYY-MM-DD')
						ELSE
							NULL
					END,
					DGCDTLR_SH.D_SH_RECEIVED_DATE_R
				)																			AS			D_RECEIVED_DATE_R,
				CDTLS.D_CLOSURE_DATE_R
			FROM
				CLAIM_DTLS CDTLS
			LEFT JOIN (
				SELECT
					DIM_GRP_CLAIM_DIR_R.N_CLAIM_SK_R,
					DIM_GRP_PARTY_DIR_R.N_PARTY_SK_R
				FROM
					DIM_GRP_CLAIM_DIR_R
				JOIN
					DIM_GRP_CLAIM_DETAIL_R
				ON
					DIM_GRP_CLAIM_DIR_R.V_ACTIVE_STATUS_R = 'Y'
					AND DIM_GRP_CLAIM_DETAIL_R.V_ACTIVE_STATUS_R = 'Y'
					AND DIM_GRP_CLAIM_DETAIL_R.N_CLAIM_SK_R = DIM_GRP_CLAIM_DIR_R.N_CLAIM_SK_R
				JOIN
					DIM_GRP_PARTY_DIR_R
				ON
					DIM_GRP_PARTY_DIR_R.V_ACTIVE_STATUS_R = 'Y'
					AND DIM_GRP_PARTY_DIR_R.N_PARTY_SK_R = DIM_GRP_CLAIM_DETAIL_R.N_INSRD_PARTY_SK_R
				JOIN (
					SELECT
						DIM_GRP_PRODUCT_R.V_COVERAGE_TYPE_CODE_R,
						MVW_PRODUCT_SK_LOOKUP.N_CLAIM_SK_R
					FROM
						DIM_GRP_PRODUCT_R
					JOIN
						MVW_PRODUCT_SK_LOOKUP
					ON
						DIM_GRP_PRODUCT_R.N_PRODUCT_SK_R = MVW_PRODUCT_SK_LOOKUP.N_PRODUCT_SK_R
						AND DIM_GRP_PRODUCT_R.V_COVERAGE_TYPE_CODE_R = '1'
				) PRD
				ON
					PRD.N_CLAIM_SK_R = DIM_GRP_CLAIM_DIR_R.N_CLAIM_SK_R
			) CLM_PRD
			ON
				CDTLS.V_COVERAGE_TYPE_CODE_R = '2'
				AND CLM_PRD.N_PARTY_SK_R = CDTLS.N_PARTY_SK_R
			LEFT JOIN (
				SELECT
					MAX(D_AUDIT_DATE_R)                                                     AS          D_AUDIT_DATE_R,
					V_CLAIM_NUMBER_R
				FROM
					DIM_GRP_BUSOBJ_AUDIT_R
				WHERE
					UPPER(TRIM(V_METHOD_R)) = 'NEW'
					AND (
							UPPER(TRIM(V_METHOD_STYLE_R)) = 'FORM'
							OR UPPER(TRIM(V_METHOD_STYLE_R)) = 'NOCONFIRM'
					)
				GROUP BY V_CLAIM_NUMBER_R
			) DGBOR
			ON
				DGBOR.V_CLAIM_NUMBER_R = CDTLS.V_CLAIM_NUMBER_R
			/* Shinka Received Date (Sep 2024) */
			LEFT JOIN (
                SELECT
                    DGCDTLR_SH_IN.N_CLAIM_SK_R,
                    COALESCE(
                        TRUNC(DGCDTLR_SH_IN.D_SH_RECEIVED_DATE_R1),
                        TRUNC(DGCDTLR_SH_IN.D_SH_RECEIVED_DATE_R2)
                    )                                                                           AS          D_SH_RECEIVED_DATE_R
                FROM (
                    SELECT
                        /*For BC- claims, there would be one-to-one mapping for the Received Dates, but for older
                        V- claims, there might be multiple Received dates based on when the claim was opened. Based on
                        discussion with John, for BC- we take the received date and for V- claims, the MIN of the received
                        date is fine (Nov 2024 */
                      --MIN(TO_TIMESTAMP(D_RECEIVED_DATE_R, 'DD-MON-YY HH:MI:SS.FF AM'))        AS          D_SH_RECEIVED_DATE_R1,
                        MIN(D_RECEIVED_DATE_R)                                                  AS          D_SH_RECEIVED_DATE_R1,
                        MIN(T_EVENT_TIMESTAMP_R)                                                AS			D_SH_RECEIVED_DATE_R2,
                        N_CLAIM_SK_R
                    FROM
                        DIM_GRP_CLAIM_DETAIL_R
                    WHERE
                        N_CLAIM_SK_R <> -1
                        AND V_SOURCE_SYSTEM_NAME_R = 'CV'
                    GROUP BY
                        N_CLAIM_SK_R
                ) DGCDTLR_SH_IN
			) DGCDTLR_SH
			ON
				DGCDTLR_SH.N_CLAIM_SK_R = CDTLS.N_CLAIM_SK_R
		)
		SELECT * FROM STD_TO_LTD_BRIDGE_CLAIMS
	);
	COMMIT;
EXCEPTION
WHEN OTHERS THEN
V_SQLERRM := SUBSTR(SQLERRM, 1, 4000);
	   RAISE_APPLICATION_ERROR(-20111, 'Raise Application Error in PRC_LOAD_STG_GRP_CLAIM_SUMMARY_COVRG_TIER_TBL_R :->' || V_SQLERRM);
END;

