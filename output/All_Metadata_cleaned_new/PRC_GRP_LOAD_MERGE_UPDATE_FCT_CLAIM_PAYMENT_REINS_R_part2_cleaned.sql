MERGE INTO FCT_BENEFIT_PAYMENT_DETAIL_OFFSET_MV_TBL FLRDR
		USING (
          SELECT DISTINCT
              N_CLAIM_SK_R,
              V_CLAIM_NUMBER_R,
              V_PRIMARY_REINSURER_R,
              D_PAID_DATE_R,
              CASE
                  WHEN N_SECONDARY_REINSURER_REINSURANCE_PCT_R < 0 THEN
                      NULL
                  ELSE
                      V_SECONDARY_REINSURER_R
              END  AS V_SECONDARY_REINSURER_R,
              CASE
                  WHEN N_TERNARY_REINSURER_REINSURANCE_PCT_R < 0 THEN
                      NULL
                  ELSE
                      V_TERNARY_REINSURER_R
              END  AS V_TERNARY_REINSURER_R,
              CASE
                  WHEN N_SECONDARY_REINSURER_REINSURANCE_PCT_R < 0
                       OR ( N_SECONDARY_REINSURER_REINSURANCE_PCT_R < 0
                            AND N_TERNARY_REINSURER_REINSURANCE_PCT_R < 0 ) THEN
                      N_PRIMARY_REINSURER_REINSURANCE_PCT_R
                  WHEN N_SECONDARY_REINSURER_REINSURANCE_PCT_R > 0
                       AND N_TERNARY_REINSURER_REINSURANCE_PCT_R < 0 THEN
                      N_PRIMARY_REINSURER_REINSURANCE_PCT_R + N_SECONDARY_REINSURER_REINSURANCE_PCT_R
                  ELSE
                      N_TOTAL_REINSURANCE_PCT_R
              END  AS N_TOTAL_REINSURANCE_PCT_R,
              N_PRIMARY_REINSURER_REINSURANCE_PCT_R,
              CASE
                  WHEN N_SECONDARY_REINSURER_REINSURANCE_PCT_R < 0 THEN
                      NULL
                  ELSE
                      N_SECONDARY_REINSURER_REINSURANCE_PCT_R
              END  AS N_SECONDARY_REINSURER_REINSURANCE_PCT_R,
              CASE
                  WHEN N_TERNARY_REINSURER_REINSURANCE_PCT_R < 0 THEN
                      NULL
                  ELSE
                      N_TERNARY_REINSURER_REINSURANCE_PCT_R
              END  AS N_TERNARY_REINSURER_REINSURANCE_PCT_R,
              N_PRIMARY_REINSURER_REINS_SHARE_PCT_R,
              CASE
                  WHEN N_SECONDARY_REINSURER_REINSURANCE_PCT_R < 0 THEN
                      NULL
                  ELSE
                      N_SECONDARY_REINSURER_REINS_SHARE_PCT_R
              END  AS N_SECONDARY_REINSURER_REINS_SHARE_PCT_R,
              CASE
                  WHEN N_TERNARY_REINSURER_REINSURANCE_PCT_R < 0 THEN
                      NULL
                  ELSE
                      N_TERNARY_REINSURER_REINS_SHARE_PCT_R
              END  AS N_TERNARY_REINSURER_REINS_SHARE_PCT_R
          FROM
              FCT_CLAIM_PAYMENT_DETAIL_BENEFIT_PAYMENT_R
          WHERE
                  N_PRIMARY_REINSURER_REINSURANCE_PCT_R > 0
              AND V_PRIMARY_REINSURER_R IS NOT NULL
      )
	SGRCPR ON ( FLRDR.N_CLAIM_SK_R = SGRCPR.N_CLAIM_SK_R
             AND FLRDR.D_PAID_DATE_R = SGRCPR.D_PAID_DATE_R
             )
