INSERT INTO FCT_RPT_CLAIM_SUMMARY_INTERMEDIATE_MV_TBL(
		N_CLAIM_SK_R,
		N_CLAIM_COVERAGE_SK_R,
		N_CLAIM_COVERAGE_GROUP_SK_R,
		V_CLAIM_IDENTIFIER_R,
		V_CLAIM_NUMBER_R,
		T_FIRST_OPEN_STATUS_EFF_DATE,
		N_PRIOR_N_REOPEN_CLAIM_CNT_R,
		PRIOR_V_CLAIM_ACTIVITY_GROUP_R,
		N_LOSS_PAYMENT_DIRECT_AMT_R	,
        T_FIRST_CLOSED_STATUS_EFF_DATE,
		D_FIRST_BENEFIT_PAYMENT_DATE_R,
		DD_CLAIM_FIRST_CLOSED_STAT_EFF_DATE,
        DD_CLAIM_FIRST_OPEN_STAT_EFF_DATE
	)
	WITH
	FIRST_BENEFIT_PAYMENT_DATE AS (
		SELECT
			TRUNC(FCPDR.D_SERVICE_PERIOD_FROM_R)			AS		D_FIRST_BENEFIT_PAYMENT_DATE_R,
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_COVERAGE_TYPE_CODE_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.V_CLAIM_NUMBER_R
		FROM (
			 SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
		) SGCSR
		LEFT JOIN (
			SELECT 
				MIN(D_PAID_DATE_R) AS D_SERVICE_PERIOD_FROM_R, 
                N_CLAIM_SK_R,
                N_CLAIM_COVERAGE_GROUP_SK_R
			FROM
				FCT_CLAIM_PAYMENT_DETAIL_R_MV_SSL
			WHERE
				UPPER(V_BENEFIT_CATEGORY_R) = 'BENEFIT'
				AND UPPER(V_PAYMENT_STATUS_R) <> 'VOID'
			GROUP BY
				N_CLAIM_SK_R,
				N_CLAIM_COVERAGE_GROUP_SK_R
		) FCPDR
		ON
			FCPDR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND FCPDR.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
	),
	MIN_OPEN_TIMESTAMP AS (
		SELECT
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_CLAIM_NUMBER_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			MIN(
				CASE
					WHEN DGCDR.V_LOB_TYPE_R IN ('LTD', 'STD', 'VPL', 'VPS') OR (DGCDR.V_SOURCE_SYSTEM_NAME_R IN ('CV', 'EIS') AND DGCDR.V_LOB_TYPE_R IN ('LIFE', 'NONS', 'WOP'))
						THEN TRUNC(DGCDTR.T_EVENT_TIMESTAMP_R)
					WHEN DGCDR.V_SOURCE_SYSTEM_NAME_R NOT IN ('CV', 'EIS') AND DGCDR.V_LOB_TYPE_R IN ('LIFE', 'NONS', 'WOP')
						THEN TRUNC(DGCCGR.T_EVENT_TIMESTAMP_R)
				END
			)					AS 			MIN_OPEN_TIMESTAMP
		FROM (
			SELECT
				*
			FROM
				STG_GRP_CLAIM_SUMMARY_R
			WHERE
				V_REASON_FLAG_R = 'Y'
		) SGCSR
		JOIN
			DIM_GRP_CLAIM_DIR_R DGCDR
		ON
			DGCDR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND DGCDR.V_ACTIVE_STATUS_R = 'Y'
		JOIN
			DIM_GRP_CLAIM_DETAIL_R DGCDTR
		ON
			DGCDTR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND DGCDTR.V_CLAIM_STATUS_REASON_CODE_R < '60'
			AND DGCDTR.V_CLAIM_STATUS_REASON_CODE_R NOT IN ('11', '22', '46')
		LEFT JOIN
			DIM_GRP_CLAIM_COVERAGE_GROUP_R DGCCGR
		ON
			DGCCGR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND DGCCGR.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
			AND DGCCGR.V_REASON_CODE_R < '60'
			AND DGCCGR.V_REASON_CODE_R NOT IN ('11', '22', '46')
		GROUP BY
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_CLAIM_NUMBER_R,
			SGCSR.V_CLAIM_IDENTIFIER_R
	),
	PAYMENTS_DURING_OPEN_STATUS AS (
		SELECT
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_CLAIM_NUMBER_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			MOT.MIN_OPEN_TIMESTAMP,
			COUNT(FCPDR.D_PAID_DATE_R) 				AS 		NO_OF_PAYMENTS
		FROM (
			SELECT
				*
			FROM
				STG_GRP_CLAIM_SUMMARY_R
			WHERE
				V_REASON_FLAG_R = 'Y'
		) SGCSR
		LEFT JOIN
			MIN_OPEN_TIMESTAMP MOT
		ON
			MOT.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND MOT.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		LEFT JOIN (
			SELECT
				N_CLAIM_SK_R,
				N_CLAIM_COVERAGE_GROUP_SK_R,
				D_PAID_DATE_R
			FROM
				FCT_CLAIM_PAYMENT_DETAIL_R_MV_SSL
			WHERE
				UPPER(V_BENEFIT_CATEGORY_R) = 'BENEFIT'
				AND UPPER(V_PAYMENT_STATUS_R) <> 'VOID'
		) FCPDR
		ON
			FCPDR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND FCPDR.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
			AND TRUNC(FCPDR.D_PAID_DATE_R) < TRUNC(MOT.MIN_OPEN_TIMESTAMP)
		GROUP BY
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_CLAIM_NUMBER_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			MOT.MIN_OPEN_TIMESTAMP
	),
    CLAIM_FIRST_OPEN_STAT_EFF_DATE AS (
		SELECT
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_COVERAGE_TYPE_CODE_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.V_CLAIM_NUMBER_R,
			CASE
				WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LTD',
					'STD',
					'VPL',
					'VPS'
					)
				THEN (
						SELECT
							MIN(DGCDTLR.T_EVENT_TIMESTAMP_R)
						FROM
							DIM_GRP_CLAIM_DIR_R DGCDR
						JOIN
							DIM_GRP_CLAIM_DETAIL_R DGCDTLR
						ON
							DGCDR.N_CLAIM_SK_R = DGCDTLR.N_CLAIM_SK_R
							AND DGCDTLR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
							AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R NOT IN ('11', '22', '46') 
                            AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R < '60'
							AND DGCDTLR.N_CLAIM_SK_R <> -1
							AND DGCDR.V_LOB_TYPE_R != 'ANNUITY'
				)
				WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LIFE',
					'NONS', 
					'WOP'
					)
                AND V_SOURCE_SYSTEM_NAME_R NOT IN ('CV', 'EIS') 
				THEN (
						SELECT
							MIN(DGCCGR.T_EVENT_TIMESTAMP_R)
						FROM
							DIM_GRP_CLAIM_COVERAGE_GROUP_R DGCCGR
						JOIN
							DIM_GRP_CLAIM_COVERAGE_R DGCCR
						ON
							DGCCGR.N_CLAIM_COVERAGE_SK_R = DGCCR.N_CLAIM_COVERAGE_SK_R
						JOIN
							DIM_GRP_CLAIM_DETAIL_R
						ON
							DGCCR.N_CLAIM_SK_R = DIM_GRP_CLAIM_DETAIL_R.N_CLAIM_SK_R
						WHERE
							DGCCGR.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
							AND DIM_GRP_CLAIM_DETAIL_R.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
							AND DGCCR.V_ACTIVE_STATUS_R = 'Y'
							AND DGCCGR.V_REASON_CODE_R < '60'
                            AND DGCCGR.V_REASON_CODE_R NOT IN ('11', '22', '46')
							AND DGCCGR.N_CLAIM_SK_R <> -1
							AND DGCCR.N_CLAIM_SK_R <> -1
							AND DIM_GRP_CLAIM_DETAIL_R.N_CLAIM_SK_R <> -1
						)
                WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LIFE',
					'NONS', 
					'WOP'
					)
                AND V_SOURCE_SYSTEM_NAME_R IN ('CV', 'EIS') 
                THEN (
                        SELECT
                            MIN(DGCDTLR.T_EVENT_TIMESTAMP_R) 
                        FROM
                            DIM_GRP_CLAIM_DIR_R DGCDR
                        JOIN
                            DIM_GRP_CLAIM_DETAIL_R DGCDTLR
                        ON
                            DGCDR.N_CLAIM_SK_R = DGCDTLR.N_CLAIM_SK_R
                            AND DGCDTLR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
                            AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R < '60'
                            AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R NOT IN ('11', '22', '46') 
                            AND DGCDTLR.N_CLAIM_SK_R <> -1
                            AND DGCDR.V_LOB_TYPE_R != 'ANNUITY'
                    )
				ELSE NULL
			END										AS			T_FIRST_OPEN_STATUS_EFF_DATE
		FROM (
            SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
        ) SGCSR
		LEFT JOIN
			DIM_GRP_CLAIM_DIR_R DGCDR1
		ON
			DGCDR1.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND DGCDR1.V_ACTIVE_STATUS_R = 'Y'
	),
    /* Decision Date Open Status Effective Date (Sep 2024) */
    DD_CLAIM_FIRST_OPEN_STAT_EFF_DATE AS (
		SELECT
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_COVERAGE_TYPE_CODE_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.V_CLAIM_NUMBER_R,
			CASE
                WHEN NVL(TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R), TO_DATE('31-DEC-2999'))  <
                    NVL(TRUNC(CPC.T_FIRST_OPEN_STATUS_EFF_DATE), TO_DATE('31-DEC-2999'))
                THEN
                    TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R)
        ELSE
            TRUNC(CPC.T_FIRST_OPEN_STATUS_EFF_DATE)
			END										AS			T_DD_FIRST_OPEN_STATUS_EFF_DATE
		FROM (
            SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
        ) SGCSR
		LEFT JOIN
			FIRST_BENEFIT_PAYMENT_DATE FBPD
		ON
			FBPD.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
            AND FBPD.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
        LEFT JOIN
            CLAIM_FIRST_OPEN_STAT_EFF_DATE CPC
        ON
            CPC.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
            AND CPC.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
	),
    CLAIM_FIRST_CLOSED_STAT_EFF_DATE AS (
		SELECT
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_COVERAGE_TYPE_CODE_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.V_CLAIM_NUMBER_R,
			CASE
                WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LTD',
					'STD',
					'VPL',
					'VPS'
					)
				THEN (
						SELECT
							MIN(DGCDTLR.T_EVENT_TIMESTAMP_R)
						FROM
							DIM_GRP_CLAIM_DIR_R DGCDR
						JOIN
							DIM_GRP_CLAIM_DETAIL_R DGCDTLR
						ON
							DGCDR.N_CLAIM_SK_R = DGCDTLR.N_CLAIM_SK_R
							AND DGCDTLR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
							AND DGCDTLR.V_CLAIM_NUMBER_R = SGCSR.V_CLAIM_NUMBER_R
							AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R >= '60'
                            AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R NOT IN ('91', '92') /* These are Error claims, no payments. Ideally should not be considered in counts. */
							AND DGCDTLR.N_CLAIM_SK_R <> -1
							AND DGCDR.V_LOB_TYPE_R != 'ANNUITY'
				)
				WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LIFE',
					'NONS',
					'WOP'
					)
                AND V_SOURCE_SYSTEM_NAME_R NOT IN ('CV', 'EIS') 
				THEN (
						SELECT
							MIN(DGCCGR.T_EVENT_TIMESTAMP_R)
						FROM
							DIM_GRP_CLAIM_COVERAGE_GROUP_R DGCCGR
						JOIN
							DIM_GRP_CLAIM_COVERAGE_R DGCCR
						ON
							DGCCGR.N_CLAIM_COVERAGE_SK_R = DGCCR.N_CLAIM_COVERAGE_SK_R
						JOIN
							DIM_GRP_CLAIM_DETAIL_R
						ON
							DGCCR.N_CLAIM_SK_R = DIM_GRP_CLAIM_DETAIL_R.N_CLAIM_SK_R
						WHERE
							DGCCGR.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
							AND DIM_GRP_CLAIM_DETAIL_R.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
                            /* AND DGCCGR.V_ACTIVE_STATUS_R = 'Y' */ 
							AND DGCCGR.V_REASON_CODE_R >= '60'
                            AND DGCCGR.V_REASON_CODE_R NOT IN ('91', '92') /* We don't need to consider 91 & 92 for Closed Date (Oct 2024) */
							AND DGCCGR.N_CLAIM_SK_R <> -1
							AND DGCCR.N_CLAIM_SK_R <> -1
							AND DIM_GRP_CLAIM_DETAIL_R.N_CLAIM_SK_R <> -1
						)
                WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LIFE',
					'NONS',
					'WOP'
					)
                AND V_SOURCE_SYSTEM_NAME_R IN ('CV', 'EIS') 
				THEN (
                        SELECT
                            MIN(DGCDTLR.D_CLOSURE_DATE_R) 
                        FROM
                            DIM_GRP_CLAIM_DIR_R DGCDR
                        JOIN
                            DIM_GRP_CLAIM_DETAIL_R DGCDTLR
                        ON
                            DGCDR.N_CLAIM_SK_R = DGCDTLR.N_CLAIM_SK_R
                            AND DGCDTLR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
                            AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R >= '60'
                            AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R NOT IN ('91', '92') 
                            AND DGCDTLR.N_CLAIM_SK_R <> -1
                            AND DGCDR.V_LOB_TYPE_R != 'ANNUITY'
						)
				ELSE NULL
			END										AS			T_FIRST_CLOSED_STATUS_EFF_DATE
		FROM (
            SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
        ) SGCSR
		LEFT JOIN
			DIM_GRP_CLAIM_DIR_R DGCDR1
		ON
			DGCDR1.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND DGCDR1.V_ACTIVE_STATUS_R = 'Y'
	),
	DD_CLAIM_FIRST_CLOSED_STAT_EFF_DATE AS (
		SELECT
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SGCSR.V_COVERAGE_TYPE_CODE_R,
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.V_CLAIM_NUMBER_R,
			CASE
                WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LTD',
					'STD',
					'VPL',
					'VPS'
					)
				THEN (
                        SELECT
                            CASE WHEN (
                                NVL(DGCDTL_IN.T_EVENT_TIMESTAMP_R, TO_DATE('31-DEC-2999')) < NVL(TRUNC(PDOS.MIN_OPEN_TIMESTAMP), TO_DATE('31-DEC-2999'))
                                AND NVL(PDOS.NO_OF_PAYMENTS, 0) = 0
                            ) THEN TRUNC(DGCDTL_IN.T_EVENT_TIMESTAMP_R)
                            ELSE
                                CASE WHEN NVL(TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R), TO_DATE('31-DEC-2999')) < NVL(TRUNC(PDOS.MIN_OPEN_TIMESTAMP), TO_DATE('31-DEC-2999'))
                                    THEN TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R)
                                ELSE NULL
                                END
                            END                                     AS  T_EVENT_TIMESTAMP_R
                        FROM(
                                SELECT
                                    MIN(DGCDTL3.T_EVENT_TIMESTAMP_R) AS T_EVENT_TIMESTAMP_R
                                FROM
                                    DIM_GRP_CLAIM_DIR_R DGCDR_IN
                                JOIN
                                    DIM_GRP_CLAIM_DETAIL_R DGCDTL3
                                ON
                                    DGCDTL3.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
                                    AND DGCDTL3.N_CLAIM_SK_R = DGCDR_IN.N_CLAIM_SK_R
									AND DGCDTL3.V_CLAIM_NUMBER_R = SGCSR.V_CLAIM_NUMBER_R
                                    AND DGCDTL3.V_CLAIM_STATUS_REASON_CODE_R >= '60'
                                    AND DGCDTL3.V_CLAIM_STATUS_REASON_CODE_R NOT IN ('91', '92')
                                    AND DGCDR_IN.V_LOB_TYPE_R != 'ANNUITY'
                            ) DGCDTL_IN
				)
				WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LIFE',
					'NONS',
					'WOP'
					)
                AND DGCDR1.V_SOURCE_SYSTEM_NAME_R NOT IN ('CV', 'EIS') 
				THEN (
						SELECT
							CASE WHEN (
								NVL(DGCCGR_IN.T_EVENT_TIMESTAMP_R, TO_DATE('31-DEC-2999')) < NVL(TRUNC(PDOS.MIN_OPEN_TIMESTAMP), TO_DATE('31-DEC-2999'))
								AND NVL(PDOS.NO_OF_PAYMENTS, 0) = 0
							) THEN TRUNC(DGCCGR_IN.T_EVENT_TIMESTAMP_R )
							ELSE
								CASE WHEN NVL(TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R), TO_DATE('31-DEC-2999')) < NVL(TRUNC(PDOS.MIN_OPEN_TIMESTAMP), TO_DATE('31-DEC-2999'))
									THEN TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R)
								ELSE NULL
								END
							END                                     AS  T_EVENT_TIMESTAMP_R
						FROM(
							SELECT
								MIN(T_EVENT_TIMESTAMP_R) AS T_EVENT_TIMESTAMP_R
							FROM
								DIM_GRP_CLAIM_COVERAGE_GROUP_R DGCCGR3
							WHERE
								DGCCGR3.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
								AND DGCCGR3.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
								AND DGCCGR3.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
								AND DGCCGR3.V_REASON_CODE_R >= '60'
								AND DGCCGR3.V_REASON_CODE_R NOT IN ('91', '92')
						) DGCCGR_IN
				)
                WHEN DGCDR1.V_LOB_TYPE_R IN (
					'LIFE',
					'NONS',
					'WOP'
					)
                AND DGCDR1.V_SOURCE_SYSTEM_NAME_R IN ('CV', 'EIS') 
				THEN (
						SELECT
							CASE WHEN (
								NVL(DGCDTL_IN2.T_EVENT_TIMESTAMP_R, TO_DATE('31-DEC-2999')) < NVL(TRUNC(PDOS.MIN_OPEN_TIMESTAMP), TO_DATE('31-DEC-2999'))
								AND NVL(PDOS.NO_OF_PAYMENTS, 0) = 0
							) THEN TRUNC(DGCDTL_IN2.T_EVENT_TIMESTAMP_R )
							ELSE
								CASE WHEN NVL(TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R), TO_DATE('31-DEC-2999')) < NVL(TRUNC(PDOS.MIN_OPEN_TIMESTAMP), TO_DATE('31-DEC-2999'))
									THEN TRUNC(FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R)
								ELSE NULL
								END
							END                                     AS  T_EVENT_TIMESTAMP_R
						FROM(
							SELECT
								MIN(DGCDTLR.D_CLOSURE_DATE_R) AS T_EVENT_TIMESTAMP_R 
							FROM
								DIM_GRP_CLAIM_DIR_R DGCDR
							JOIN
								DIM_GRP_CLAIM_DETAIL_R DGCDTLR
							ON
								DGCDR.N_CLAIM_SK_R = DGCDTLR.N_CLAIM_SK_R
								AND DGCDTLR.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
								AND DGCDTLR.V_CLAIM_NUMBER_R = SGCSR.V_CLAIM_NUMBER_R
								AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R >= '60'
								AND DGCDTLR.V_CLAIM_STATUS_REASON_CODE_R NOT IN ('91', '92') 
								AND DGCDTLR.N_CLAIM_SK_R <> -1
								AND DGCDR.V_LOB_TYPE_R != 'ANNUITY'
							) DGCDTL_IN2
				)
				ELSE NULL
			END										AS			T_DD_FIRST_CLOSED_STATUS_EFF_DATE
		FROM (
            SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
        ) SGCSR
		LEFT JOIN
			FIRST_BENEFIT_PAYMENT_DATE FBPD
		ON
			FBPD.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND FBPD.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		LEFT JOIN
			DIM_GRP_CLAIM_DIR_R DGCDR1
		ON
			DGCDR1.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND DGCDR1.V_ACTIVE_STATUS_R = 'Y'
		LEFT JOIN
			PAYMENTS_DURING_OPEN_STATUS PDOS
		ON
			PDOS.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
			AND PDOS.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
	),
	PRIOR_RECORDS_LOOKUP AS (
		SELECT
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			SUM(FRCSR.N_REOPEN_CLAIM_COUNT_R)		AS 		N_PRIOR_N_REOPEN_CLAIM_CNT_R,
			MAX(FRCSR.V_CLAIM_ACTIVITY_GROUP_R)		AS		PRIOR_V_CLAIM_ACTIVITY_GROUP_R
		FROM (
            SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
        ) SGCSR
		LEFT JOIN (
            SELECT
                V_CLAIM_IDENTIFIER_R,
                MAX(V_CLAIM_ACTIVITY_GROUP_R)		AS		V_CLAIM_ACTIVITY_GROUP_R,
                MAX(N_REOPEN_CLAIM_COUNT_R)			AS 		N_REOPEN_CLAIM_COUNT_R
            FROM(
                SELECT
                    V_CLAIM_IDENTIFIER_R,
                    V_CLAIM_ACTIVITY_GROUP_R,
                    N_REOPEN_CLAIM_COUNT_R
                FROM (
                    SELECT 
                        V_CLAIM_IDENTIFIER_R,
                        V_CLAIM_ACTIVITY_GROUP_R,
                        N_REOPEN_CLAIM_COUNT_R,
                        RANK() OVER(PARTITION BY V_CLAIM_IDENTIFIER_R ORDER BY D_CYCLE_DATE_R DESC) RNK
                    FROM
                        FCT_RPT_CLAIM_SUMMARY_R
                    WHERE
                        D_CYCLE_DATE_R <= D_PRIOR_FISCAL_DATE
                ) WHERE RNK=1 
            ) FRCSR_PRIOR
            GROUP BY
                V_CLAIM_IDENTIFIER_R
		) FRCSR
		ON
			FRCSR.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
		GROUP BY
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
	),
	CLAIM_PAYMENT_COUNTS AS (
		SELECT
			SGCSR.V_CLAIM_IDENTIFIER_R,
			SGCSR.N_CLAIM_SK_R,
			SGCSR.N_CLAIM_COVERAGE_SK_R,
			SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
			FCPDTLR4.N_PAID_CLAIM_BENEFITS_R			AS		N_LOSS_PAYMENT_DIRECT_AMT_R
		FROM (
            SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
        ) SGCSR
		LEFT JOIN
		(SELECT
					CASE WHEN CP.v_cov_group_id_r IS NULL THEN upper(TRIM(CP.v_claim_number_r))
					ELSE upper(TRIM(CP.v_claim_number_r || '-' || lpad(CP.v_cov_group_id_r, 2, 0))) END AS v_claim_identifier_r,
CASE
WHEN NVL(CP.V_SOURCE_SYSTEM_NAME_R,'PACS') = 'CV' and  CP.V_COVERAGE_CODE_R not IN ('VAI', 'VCI', 'VHI') THEN
NVL(SUM(CASE
WHEN CP.v_record_type_r = 'Adjustment'
THEN (
CASE
WHEN CP.v_benefit_group_r IS NOT NULL
THEN NVL(CP.N_PAID_AMOUNT_R, 0)
ELSE 0
END
)
WHEN CP.V_BENEFIT_CODE_R IN (
'FIC'
,'MED'
)
THEN (CP.N_PAID_AMOUNT_R)
ELSE NVL(CP.N_PAID_AMOUNT_R, 0)
END),0)
ELSE
					CASE
						WHEN CP.V_COVERAGE_CODE_R IN ('VAI', 'VCI', 'VHI') THEN
							(SUM(CP.N_PAID_AMOUNT_R))
						ELSE
							NVL(SUM(
								CASE
									WHEN CP.V_RECORD_TYPE_R = 'Redirect' THEN CP.N_PAID_AMOUNT_R
									WHEN CP.V_BENEFIT_CODE_R IN ('FIC', 'MED') AND CP.V_RECORD_TYPE_R = 'Benefit Payment' THEN CP.N_PAID_CLAIM_BENEFITS_R * -1
									WHEN CP.V_BENEFIT_CODE_R IN ('FIC', 'MED') AND CP.V_RECORD_TYPE_R = 'Adjustment' THEN CP.N_PAID_CLAIM_BENEFITS_R * -1
									WHEN CP.V_BENEFIT_GROUP_R IN ('098', '097', '099', '297', '298') THEN 0
									ELSE CP.N_PAID_CLAIM_BENEFITS_R
								END),
								0
								)
					END END AS N_PAID_CLAIM_BENEFITS_R
				FROM
					ATOMIC.FCT_CLAIM_PAYMENT_DETAIL_R_MV_SSL CP
					LEFT JOIN ATOMIC.DIM_TIME_R  T ON CP.D_PAID_DATE_R = T.D_CALENDAR_DATE_R
				WHERE 
                        T.n_fiscal_month_r  = TO_NUMBER(TO_CHAR(D_CURR_FISCAL_DATE, 'MM'))
                       AND T.n_fiscal_year_r   = TO_NUMBER(TO_CHAR(D_CURR_FISCAL_DATE, 'YYYY'))
				GROUP BY
					CASE WHEN CP.v_cov_group_id_r IS NULL THEN upper(TRIM(CP.v_claim_number_r))
					ELSE upper(TRIM(CP.v_claim_number_r || '-' || lpad(CP.v_cov_group_id_r, 2, 0))) END,
                    CP.V_COVERAGE_CODE_R,NVL(CP.V_SOURCE_SYSTEM_NAME_R,'PACS')
		)FCPDTLR4
		ON
			FCPDTLR4.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
	)
	SELECT
		SGCSR.N_CLAIM_SK_R,
		SGCSR.N_CLAIM_COVERAGE_SK_R,
		SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R,
		SGCSR.V_CLAIM_IDENTIFIER_R,
		SGCSR.V_CLAIM_NUMBER_R,
		CFOSED.T_FIRST_OPEN_STATUS_EFF_DATE,
		PRL.N_PRIOR_N_REOPEN_CLAIM_CNT_R,
		PRL.PRIOR_V_CLAIM_ACTIVITY_GROUP_R,
		CPC.N_LOSS_PAYMENT_DIRECT_AMT_R,
        CFCSED.T_FIRST_CLOSED_STATUS_EFF_DATE,
		FBPD.D_FIRST_BENEFIT_PAYMENT_DATE_R,
		TRUNC(DCFCSED.T_DD_FIRST_CLOSED_STATUS_EFF_DATE) AS DD_CLAIM_FIRST_CLOSED_STAT_EFF_DATE,
        TRUNC(DCFOSED.T_DD_FIRST_OPEN_STATUS_EFF_DATE)  AS  DD_CLAIM_FIRST_OPEN_STAT_EFF_DATE
	FROM (
            SELECT
                *
            FROM
                STG_GRP_CLAIM_SUMMARY_R
            WHERE
                V_REASON_FLAG_R = 'Y'
    ) SGCSR
	LEFT JOIN
		CLAIM_FIRST_OPEN_STAT_EFF_DATE CFOSED
	ON
		CFOSED.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND CFOSED.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
		AND CFOSED.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		AND CFOSED.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
	LEFT JOIN
		PRIOR_RECORDS_LOOKUP PRL
	ON
		PRL.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND PRL.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
		AND PRL.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		AND PRL.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
	LEFT JOIN
		CLAIM_PAYMENT_COUNTS CPC
	ON
		CPC.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND CPC.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
		AND CPC.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		AND CPC.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
    LEFT JOIN
        CLAIM_FIRST_CLOSED_STAT_EFF_DATE CFCSED
    ON
        CFCSED.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND CFCSED.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
		AND CFCSED.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		AND CFCSED.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
	LEFT JOIN
		FIRST_BENEFIT_PAYMENT_DATE FBPD
	ON
		FBPD.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND FBPD.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
		AND FBPD.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		AND FBPD.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
	LEFT JOIN
		DD_CLAIM_FIRST_CLOSED_STAT_EFF_DATE DCFCSED
	ON
		DCFCSED.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND DCFCSED.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
		AND DCFCSED.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		AND DCFCSED.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R
    LEFT JOIN
        DD_CLAIM_FIRST_OPEN_STAT_EFF_DATE DCFOSED
    ON
        DCFOSED.N_CLAIM_SK_R = SGCSR.N_CLAIM_SK_R
		AND DCFOSED.N_CLAIM_COVERAGE_SK_R = SGCSR.N_CLAIM_COVERAGE_SK_R
		AND DCFOSED.N_CLAIM_COVERAGE_GROUP_SK_R = SGCSR.N_CLAIM_COVERAGE_GROUP_SK_R
		AND DCFOSED.V_CLAIM_IDENTIFIER_R = SGCSR.V_CLAIM_IDENTIFIER_R;
	COMMIT;
END;