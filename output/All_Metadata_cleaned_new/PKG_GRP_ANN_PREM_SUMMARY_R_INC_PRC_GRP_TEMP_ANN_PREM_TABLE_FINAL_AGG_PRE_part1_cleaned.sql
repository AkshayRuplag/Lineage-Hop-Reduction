insert  INTO TEMP_ANN_PREM_TABLE_FINAL_AGG_PRE
(
BASEKEYS
,D_CYCLE_DATE_R
,CYCLE_YEAR_R
,CYCLE_MONTH_R
,N_POLICY_SK_R
,V_POLICY_NUMBER_R
,V_CUSTOMER_BILL_GROUP_R
,N_CUST_PARTY_SK_R
,N_POLICY_BILLGROUP_ID_R
,D_DUE_DATE_R
,N_ANNUALIZED_PREMIUM_R
,N_GROSS_LIVES_R
,N_VOLUME_R
,V_PLAN_TYPE_R
,V_CLASS_ID_R
,V_MASTER_CUSTOMER_NUM_R
,V_POLICY_PREFIX_R
,V_COVERAGE_CODE_R
,V_SHORT_NAME_R
,V_POLICY_STATUS_R
,V_PREMIUM_MODE_R
,N_PREMIUM_MODE_FACTOR_R
,N_COVERAGE_LEVEL_R
)
Select * from
(
WITH BATCH_DATE AS (
Select  * from
( SELECT D_CALENDAR_DATE_R,
RANK() OVER ( ORDER BY D_CALENDAR_DATE_R DESC) DATE_RANK
from
atomic.DIM_TIME_R
where
V_END_OF_FISCAL_MONTH_IND_R = 'Y' AND D_CALENDAR_DATE_R < ld_V_BATCH_ID_R1
) WHERE DATE_RANK < 3
),
BATCH_DATE_QTR AS (
Select  * from
( SELECT D_CALENDAR_DATE_R,
RANK() OVER ( ORDER BY D_CALENDAR_DATE_R DESC) DATE_RANK
from
atomic.DIM_TIME_R
where
V_END_OF_FISCAL_QUARTER_IND_R = 'Y' AND D_CALENDAR_DATE_R < ld_V_BATCH_ID_R2
) WHERE DATE_RANK < 2
),
BATCH_DATE_YTD AS (
Select  * from
( SELECT D_CALENDAR_DATE_R,
RANK() OVER ( ORDER BY D_CALENDAR_DATE_R DESC) DATE_RANK
from
atomic.DIM_TIME_R
where
V_END_OF_FISCAL_YEAR_IND_R = 'Y' AND D_CALENDAR_DATE_R < ld_V_BATCH_ID_R2
) WHERE DATE_RANK < 2
),
FCT_GRP_BILLING_POLICY_DTL_R_table AS
(
Select  * from atomic.STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR  WHERE
atomic.STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR.V_DELETE_BY_R IS NULL AND
(atomic.STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR.V_POLICY_STATUS_R <> 'Terminated'  OR
(atomic.STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR.V_POLICY_STATUS_R = 'Terminated' AND atomic.STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR.D_STATUS_REASON_DATE_R > (SELECT BATCH_DATE.D_CALENDAR_DATE_R FROM BATCH_DATE WHERE DATE_RANK = 1))
)
)
,
DIM_GRP_BILLING_POL_BILLGRP_R_TABLE AS
(
Select  * from atomic.DIM_GRP_BILLING_POL_BILLGRP_R DIM_GRP_BILLING_POL_BILLGRP_R
inner join STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR
on STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR.N_POLICY_SK_R = DIM_GRP_BILLING_POL_BILLGRP_R.N_POLICY_SK_R
WHERE
DIM_GRP_BILLING_POL_BILLGRP_R.V_SOURCE_SYSTEM_NAME_R='VUE'
AND                                       
(atomic.DIM_GRP_BILLING_POL_BILLGRP_R.V_BILL_GROUP_STATUS_R <> 'Terminated' OR
(atomic.DIM_GRP_BILLING_POL_BILLGRP_R.V_BILL_GROUP_STATUS_R = 'Terminated' AND (atomic.DIM_GRP_BILLING_POL_BILLGRP_R.D_STATUS_DATE_R > (SELECT BATCH_DATE.D_CALENDAR_DATE_R FROM BATCH_DATE WHERE DATE_RANK = 1)
OR  atomic.DIM_GRP_BILLING_POL_BILLGRP_R.D_STATUS_DATE_R = STG_FCT_GRP_BILLING_POLICY_DTL_R_INCR.D_STATUS_DATE_R)
))
)
,
ANN_PREM_TABLE_FINAL_BASE AS (
SELECT  distinct
(SELECT BATCH_DATE.D_CALENDAR_DATE_R FROM BATCH_DATE WHERE DATE_RANK = 1) AS D_CYCLE_DATE_R,
EXTRACT(YEAR FROM (SELECT BATCH_DATE.D_CALENDAR_DATE_R FROM BATCH_DATE WHERE DATE_RANK = 1)) CYCLE_YEAR_R,
EXTRACT(MONTH FROM (SELECT BATCH_DATE.D_CALENDAR_DATE_R FROM BATCH_DATE WHERE DATE_RANK = 1)) CYCLE_MONTH_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_POLICY_SK_R,
DIM_GRP_POLICY_DIR_R.V_POLICY_NUMBER_R,
DIM_GRP_POLICY_DIR_R.V_POLICY_PREFIX_R,
atomic.FCT_GRP_POLICY_R.N_CUST_PARTY_SK_R,
FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_SRC_POLICY_BILLGROUP_ID_R,
DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.N_POLICY_BILLGROUP_ID_R,
atomic.DIM_GRP_PARTY_R.V_MASTER_CUSTOMER_NUM_R V_MASTER_CUSTOMER_NUM_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.D_TRANSACTION_DATE_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.V_PREM_PAYMENT_DELETE_BY_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.D_DUE_DATE_R,
FCT_BILLING_POLICY_PREMIUM_R_TABLE.v_uSER_NAME_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_AMOUNT_PAID_R N_ANNUALIZED_PREMIUM_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_LIVES_R AS N_GROSS_LIVES_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_VOLUME_R,
atomic.DIM_GRP_PRODUCT_R.V_COVERAGE_CODE_R V_COVERAGE_CODE_R,
DIM_BILL_PLAN.V_PLAN_TYPE_R AS V_PLAN_TYPE_R,
DIM_BILL_PLAN.V_CLASS_R AS V_CLASS_ID_R,
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.V_BILLGROUPNUMBER_R AS V_CUSTOMER_BILL_GROUP_R,
DIM_GRP_CARRIER_R.V_SHORT_NAME_R,
FCT_GRP_BILLING_POLICY_DTL_R_table.V_POLICY_STATUS_R,
DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R AS V_PREMIUM_MODE_R,
FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_SRC_CLASS_ID_R,
FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_Months_paid_r,
CASE
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = 'MONTHLY' THEN 12.0
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = 'QUARTERLY' THEN 4.0
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = 'SEMIANNUALLY' THEN 2.0
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = 'NINTHLY' THEN 12 / 9
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = 'TENTHLY' THEN 12 / 10
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = 'ELEVENTH' THEN 12 / 11
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = 'ANNUALLY' THEN 1
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = '3 YEARS PRE-PAID' THEN 1.0 / 3
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = '3 YEARS WITH INSTALLMENT' THEN 1.0
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = '5 YEARS PRE-PAID' THEN 0.2
WHEN UPPER(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.V_PREMIUM_MODE1_R) = '5 YEARS WITH INSATLLMENT' THEN 1.0
END AS N_PREMIUM_MODE_FACTOR_R,
atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R,
CASE
WHEN atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R = 'Basic Life'
OR atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R = 'SR' THEN 1
WHEN atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R = 'VAR' THEN 2
WHEN atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R = 'LTD' THEN 3
WHEN atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R = 'Supplemental Life' THEN 4
WHEN atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R = 'STD' THEN 5
WHEN atomic.DIM_GRP_PRODUCT_R.V_COVERAGE_DESC_R ='STATE MEDICAL LEAVE' THEN 5
WHEN atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R like 'Basic AD' || '&' || 'D%' THEN 6
WHEN atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R like 'Supplemental AD' || '&' || 'D%'
OR atomic.DIM_GRP_PRODUCT_R.V_BASIC_PRODUCT_LINE_CODE_R like 'Dependent Life%' THEN 7
ELSE 8
END AS N_COVERAGE_LEVEL_R,
N_SRC_PREMIUM_PAYMENT_ID_R,
FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_POLICY_SK_R || DIM_GRP_PRODUCT_R.V_COVERAGE_CODE_R || DIM_BILL_PLAN.V_PLAN_TYPE_R || V_CLASS_R || V_BILLGROUPNUMBER_R AS BASEKEYS,
FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_SRC_POLICY_ID_R,FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_SRC_COVERAGE_ID_R
FROM
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE FCT_BILLING_POLICY_PREMIUM_R_TABLE
LEFT OUTER JOIN (SELECT V_POLICY_NUMBER_R, V_POLICY_PREFIX_R, N_POLICY_SK_R,N_POLICY_VERSION_NUMBER_R
 FROM atomic.DIM_GRP_POLICY_DIR_R WHERE V_ACTIVE_STATUS_R = 'Y') DIM_GRP_POLICY_DIR_R
ON atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_POLICY_SK_R = DIM_GRP_POLICY_DIR_R.N_POLICY_SK_R
inner JOIN DIM_GRP_BILLING_POL_BILLGRP_R_TABLE ON DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.N_POLICY_BILLGROUP_ID_R= FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_SRC_POLICY_BILLGROUP_ID_R
AND  (SELECT trunc(BATCH_DATE.D_CALENDAR_DATE_R) FROM BATCH_DATE WHERE DATE_RANK = 1) >= trunc(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.D_RECORD_START_DATE_R) AND
(SELECT trunc(BATCH_DATE.D_CALENDAR_DATE_R) FROM BATCH_DATE WHERE DATE_RANK = 1) < trunc(DIM_GRP_BILLING_POL_BILLGRP_R_TABLE.D_RECORD_END_DATE_R)
LEFT OUTER JOIN (SELECT N_POLICY_SK_R, V_PLAN_TYPE_R,V_CLASS_R,V_BILL_PLAN_CODE FROM atomic.DIM_BILL_PLAN WHERE V_ACTIVE_STATUS_R = 'Y') DIM_BILL_PLAN
ON atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_POLICY_SK_R = DIM_BILL_PLAN.N_POLICY_SK_R
AND DIM_BILL_PLAN.V_BILL_PLAN_CODE=FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_SRC_CLASS_ID_R
INNER JOIN FCT_GRP_BILLING_POLICY_DTL_R_table ON atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_SRC_POLICY_ID_R = FCT_GRP_BILLING_POLICY_DTL_R_table.N_POLICY_ID_R  
LEFT OUTER JOIN (SELECT N_CARRIER_ID_R,V_SHORT_NAME_R FROM atomic.DIM_GRP_CARRIER_R WHERE V_SOURCE_SYSTEM_NAME_R='VUE' ) DIM_GRP_CARRIER_R
ON FCT_GRP_BILLING_POLICY_DTL_R_table.N_CARRIER_ID_R = DIM_GRP_CARRIER_R.N_CARRIER_ID_R
LEFT OUTER JOIN atomic.DIM_GRP_PRODUCT_R DIM_GRP_PRODUCT_R ON atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.V_COVERAGECODE_R = atomic.DIM_GRP_PRODUCT_R.V_COVERAGE_CODE_R
LEFT OUTER JOIN atomic.FCT_GRP_POLICY_R FCT_GRP_POLICY_R ON atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.N_POLICY_SK_R = atomic.FCT_GRP_POLICY_R.N_POLICY_SK_R AND DIM_GRP_POLICY_DIR_R.N_POLICY_VERSION_NUMBER_R=atomic.FCT_GRP_POLICY_R.N_VERSION_NUMBER_R
left outer join atomic.DIM_GRP_PARTY_R DIM_GRP_PARTY_R  ON atomic.FCT_GRP_POLICY_R.N_CUST_PARTY_SK_R = atomic.DIM_GRP_PARTY_R.N_PARTY_SK_R AND atomic.DIM_GRP_PARTY_R.V_ACTIVE_STATUS_R = 'Y'
WHERE
 atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.V_SOURCE_SYSTEM_NAME_R !='MGIS' AND 
atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.V_PREM_PAYMENT_DELETE_BY_R IS NULL
AND (NVL(UPPER(FCT_BILLING_POLICY_PREMIUM_R_TABLE.v_uSER_NAME_R), 'NA') <> 'SUSPENSE ADJUSTMENT')
AND atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE.D_TRANSACTION_DATE_R <= (SELECT BATCH_DATE.D_CALENDAR_DATE_R FROM BATCH_DATE WHERE DATE_RANK = 1)
)
,
ANN_PREM_TABLE_MAX_DUE_DATE_TABLE AS (
SELECT MAX(D_DUE_DATE_R) D_DUE_DATE_R,N_SRC_POLICY_ID_R,N_SRC_POLICY_BILLGROUP_ID_R,N_SRC_COVERAGE_ID_R  FROM (
SELECT P1.D_DUE_DATE_R, SUM(P1.N_AMOUNT_PAID_R), P1.N_SRC_POLICY_ID_R, P1.N_SRC_POLICY_BILLGROUP_ID_R, P1.N_SRC_COVERAGE_ID_R    
FROM atomic.FCT_BILLING_POLICY_PREMIUM_R_TABLE P1
WHERE
P1.V_SOURCE_SYSTEM_NAME_R !='MGIS'  AND 
P1.D_TRANSACTION_DATE_R <= (SELECT BATCH_DATE.D_CALENDAR_DATE_R FROM BATCH_DATE WHERE DATE_RANK = 1)
AND
(nvl(P1.V_USER_NAME_R,'aa') <> 'Suspense Adjustment')
GROUP BY P1.N_SRC_POLICY_ID_R, P1.N_SRC_POLICY_BILLGROUP_ID_R, P1.D_DUE_DATE_R, P1.N_SRC_COVERAGE_ID_R
HAVING SUM(P1.N_AMOUNT_PAID_R) > 0
)
group by N_SRC_POLICY_ID_R,N_SRC_POLICY_BILLGROUP_ID_R,N_SRC_COVERAGE_ID_R
)
,
ANN_PREM_TABLE_SUM_TABLE AS (
SELECT
ANN_PREM_TABLE_FINAL_BASE.D_DUE_DATE_R,SUM(ANN_PREM_TABLE_FINAL_BASE.N_ANNUALIZED_PREMIUM_R) AS N_AMOUNT_PAID_R, ANN_PREM_TABLE_FINAL_BASE.BASEKEYS
FROM
ANN_PREM_TABLE_FINAL_BASE
inner join ANN_PREM_TABLE_MAX_DUE_DATE_TABLE
on ANN_PREM_TABLE_FINAL_BASE.N_SRC_POLICY_ID_R = ANN_PREM_TABLE_MAX_DUE_DATE_TABLE.N_SRC_POLICY_ID_R
and ANN_PREM_TABLE_FINAL_BASE.N_SRC_POLICY_BILLGROUP_ID_R = ANN_PREM_TABLE_MAX_DUE_DATE_TABLE.N_SRC_POLICY_BILLGROUP_ID_R
and ANN_PREM_TABLE_FINAL_BASE.N_SRC_COVERAGE_ID_R = ANN_PREM_TABLE_MAX_DUE_DATE_TABLE.N_SRC_COVERAGE_ID_R
and ANN_PREM_TABLE_FINAL_BASE.D_DUE_DATE_R = ANN_PREM_TABLE_MAX_DUE_DATE_TABLE.D_DUE_DATE_R
GROUP BY ANN_PREM_TABLE_FINAL_BASE.BASEKEYS, ANN_PREM_TABLE_FINAL_BASE.D_DUE_DATE_R
)
,
ANN_PREM_TABLE_MAX_TABLE AS (
SELECT
MAX(ANN_PREM_TABLE_SUM_TABLE.D_DUE_DATE_R) AS D_DUE_DATE_R, BASEKEYS
FROM
ANN_PREM_TABLE_SUM_TABLE
WHERE
ANN_PREM_TABLE_SUM_TABLE.N_AMOUNT_PAID_R<>0
GROUP BY BASEKEYS
)
,
ANN_PREM_TABLE_FINAL_AGG_PRE AS (
    SELECT
        ANN_PREM_TABLE_FINAL_BASE.BASEKEYS,
        D_CYCLE_DATE_R,
        CYCLE_YEAR_R,
        CYCLE_MONTH_R,
        N_POLICY_SK_R,
        V_POLICY_NUMBER_R,
        V_CUSTOMER_BILL_GROUP_R,
        N_CUST_PARTY_SK_R,
		N_POLICY_BILLGROUP_ID_R,
        ANN_PREM_TABLE_FINAL_BASE.D_DUE_DATE_R,
        SUM(N_ANNUALIZED_PREMIUM_R) * N_PREMIUM_MODE_FACTOR_R AS N_ANNUALIZED_PREMIUM_R,
        SUM(N_GROSS_LIVES_R) AS N_GROSS_LIVES_R,
        ROUND(SUM(N_VOLUME_R)) AS N_VOLUME_R,
        V_PLAN_TYPE_R,
        V_CLASS_ID_R,
        V_MASTER_CUSTOMER_NUM_R,
        V_POLICY_PREFIX_R,
        V_COVERAGE_CODE_R,
        V_SHORT_NAME_R,
        V_POLICY_STATUS_R,
        V_PREMIUM_MODE_R,
        N_PREMIUM_MODE_FACTOR_R,
        N_COVERAGE_LEVEL_R
    FROM
        ANN_PREM_TABLE_FINAL_BASE
        INNER JOIN ANN_PREM_TABLE_MAX_TABLE
        ON ANN_PREM_TABLE_FINAL_BASE.BASEKEYS=ANN_PREM_TABLE_MAX_TABLE.BASEKEYS
        AND ANN_PREM_TABLE_FINAL_BASE.D_DUE_DATE_R=ANN_PREM_TABLE_MAX_TABLE.D_DUE_DATE_R
    GROUP BY
        ANN_PREM_TABLE_FINAL_BASE.BASEKEYS,
         D_CYCLE_DATE_R,
		 N_POLICY_BILLGROUP_ID_R,
        CYCLE_YEAR_R,
        CYCLE_MONTH_R,
        N_POLICY_SK_R,
        V_POLICY_NUMBER_R,
        V_CUSTOMER_BILL_GROUP_R,
        N_CUST_PARTY_SK_R,
        ANN_PREM_TABLE_FINAL_BASE.D_DUE_DATE_R,
        V_PLAN_TYPE_R,
        V_CLASS_ID_R,
        V_MASTER_CUSTOMER_NUM_R,
        V_POLICY_PREFIX_R,
        V_COVERAGE_CODE_R,
        V_SHORT_NAME_R,
        V_POLICY_STATUS_R,
        V_PREMIUM_MODE_R,
        N_PREMIUM_MODE_FACTOR_R,
        N_COVERAGE_LEVEL_R
)
,
final_table_excl as
(select ft.* from ANN_PREM_TABLE_FINAL_AGG_PRE ft where not exists
(select  1 from VW_STG_RPT_ANN_PREM_EXCLUSION_R_MV RE 
where
ft.D_CYCLE_DATE_R = nvl(RE.D_CYCLE_DATE_R, sysdate)
and NVL(ft.V_POLICY_NUMBER_R, 'AA') = nvl(RE.V_POLICY_NUMBER_R, 'AA')
and NVL(ft.V_CUSTOMER_BILL_GROUP_R, 'AA') = nvl(RE.V_CUSTOMER_BILL_GROUP_R, 'AA')
))
Select  * from final_table_excl
) A;