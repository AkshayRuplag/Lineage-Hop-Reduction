            || LC_SQLERRM,
            LN_N_BATCH_ID_R,
            &apos;PRC_GRP_LOAD_FCT_LG_RESERVE_DETAILS_R_INCR_PREMIUM&apos;,
            &apos;PRC_GRP_LOAD_FCT_LG_RESERVE_DETAILS_R_INCR_PREMIUM&apos;
